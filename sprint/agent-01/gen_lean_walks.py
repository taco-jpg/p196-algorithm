"""Generate Lean modules carrying the forward-walk obstruction data (untrusted
data; the kernel re-executes every walk).

Usage: python3 gen_lean_walks.py K walks.tsv start_word BLOCK BLOCKS_PER_FILE OUTDIR
Writes OUTDIR/W{K}Start.lean, W{K}Data###.lean (several blocks each, one
kernel check per block to keep peak memory low), and W{K}Final.lean.
"""
import sys, os

K = int(sys.argv[1])
rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[2])]
start = sys.argv[3]
BL = int(sys.argv[4])
BPF = int(sys.argv[5])
out = sys.argv[6]
os.makedirs(out, exist_ok=True)
ns = 'Sprint.Agent01'
hdr = '/-! Generated by sprint/agent-01/gen_lean_walks.py; untrusted data, kernel-checked use. -/\n'
rows.sort(key=lambda r: int(r[0]))

with open(f'{out}/W{K}Start.lean', 'w') as f:
    f.write(f'''import P196.Sprint.Agent01.ForwardWalk

{hdr}
namespace {ns}
open SevenColumnProjection Agent124.Forward

/-- Width-{K} projection (pair sums q_0..q_{K - 1}) of `orbit 196 100`. -/
def start{K} : List Nat := [{start}]

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
theorem start{K}_eq : wordPrefix q100 {K} = start{K} := by decide +kernel

end {ns}

#print axioms {ns}.start{K}_eq
''')

blocks = [rows[i:i + BL] for i in range(0, len(rows), BL)]
files = [list(range(i, min(i + BPF, len(blocks)))) for i in range(0, len(blocks), BPF)]
fnames = []
for fi, bids in enumerate(files):
    nm = f'W{K}Data{fi:03d}'
    fnames.append(nm)
    parts = []
    for b in bids:
        ents = ',\n  '.join(f'([{",".join(p)}], [{",".join(bits)}])' for p, L, tgt, bits in blocks[b])
        parts.append(f'''/-- Block {b}: {len(blocks[b])} entries (prefix, inner-carry walk from `start{K}`). -/
def b{K}_{b:03d} : List (List Nat × List Nat) := [
  {ents}]

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
theorem b{K}_{b:03d}_ok : b{K}_{b:03d}.all (entryOK {K} start{K}) = true := by
  decide +kernel
''')
    with open(f'{out}/{nm}.lean', 'w') as f:
        f.write(f'''import P196.Sprint.Agent01.W{K}Start

{hdr}
namespace {ns}

''' + '\n'.join(parts) + f'''
end {ns}

''' + ''.join(f'#print axioms {ns}.b{K}_{b:03d}_ok\n' for b in bids))

imports = '\n'.join(f'import P196.Sprint.Agent01.{n}' for n in fnames)
blist = ', '.join(f'b{K}_{b:03d}' for b in range(len(blocks)))
oks = ', '.join(f'b{K}_{b:03d}_ok' for b in range(len(blocks)))
with open(f'{out}/W{K}Final.lean', 'w') as f:
    f.write(f'''{imports}

{hdr}
namespace {ns}
open Agent124.CodeCert Agent124.Forward Agent124.PrefixL SevenColumnProjection

/-- All width-{K} forward-walk blocks. -/
def blocks{K} : List (List (List Nat × List Nat)) := [{blist}]

theorem blocks{K}_ok : blocks{K}.all (fun b => b.all (entryOK {K} start{K})) = true := by
  simp only [blocks{K}, List.all_cons, List.all_nil, {oks}, Bool.and_self]

/-- All entries. -/
def walks{K} : List (List Nat × List Nat) := blocks{K}.flatten

/-- The obstructed prefixes, as four-digit numbers. -/
def obstructed{K} : List Nat := walks{K}.map (fun e => e.1.foldl (fun a d => 10 * a + d) 0)

/-- Strictly increasing check. -/
def incB : List Nat → Bool
  | a :: b :: l => Nat.blt a b && incB (b :: l)
  | _ => true

theorem incB_lt : ∀ (a : Nat) (l : List Nat), incB (a :: l) = true → ∀ x ∈ l, a < x
  | _, [], _, x, hx => by simp at hx
  | a, b :: l, h, x, hx => by
      simp only [incB, Bool.and_eq_true, Nat.blt_eq] at h
      rcases List.mem_cons.mp hx with rfl | hx
      · exact h.1
      · exact Nat.lt_trans h.1 (incB_lt b l h.2 x hx)

theorem nodup_of_incB : ∀ l : List Nat, incB l = true → l.Nodup
  | [], _ => List.nodup_nil
  | a :: l, h => by
      refine List.nodup_cons.mpr ⟨fun ha => Nat.lt_irrefl a (incB_lt a l h a ha), ?_⟩
      cases l with
      | nil => exact List.nodup_nil
      | cons b l =>
          simp only [incB, Bool.and_eq_true] at h
          exact nodup_of_incB _ h.2

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
theorem obstructed{K}_length : obstructed{K}.length = {len(rows)} := by decide +kernel

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
theorem obstructed{K}_inc : incB obstructed{K} = true := by decide +kernel

theorem obstructed{K}_nodup : obstructed{K}.Nodup := nodup_of_incB _ obstructed{K}_inc

/-- For each listed four-digit prefix (entry `e.1`, digits most significant
first): every forward-closed code set of width {K} that contains the width-{K}
projection of `orbit 196 100` contains a possible last-predecessor projection
(`initialWordsL {K} e.1`) of a palindrome beginning with `e.1`.  Hence the
forward-invariant method at width {K} from time 100 cannot exclude any of the
{len(rows)} prefixes.  (Statement about the abstraction only.) -/
theorem forward_obstruction{K} : ∀ e ∈ walks{K}, ∃ w ∈ initialWordsL {K} e.1,
    ∀ t : CodeTree, t.All (fun c _ => fwdOK t {K} c = true) →
      Mem t (wordPrefix q100 {K}) → Mem t w := by
  intro e he
  rw [walks{K}, List.mem_flatten] at he
  obtain ⟨b, hb, heb⟩ := he
  exact forward_cannot_exclude (by decide) start{K}_eq b
    (List.all_eq_true.mp blocks{K}_ok b hb) e heb

end {ns}

#print axioms {ns}.blocks{K}_ok
#print axioms {ns}.obstructed{K}_length
#print axioms {ns}.obstructed{K}_nodup
#print axioms {ns}.forward_obstruction{K}
''')
print(f'wrote {len(fnames)} data modules, {len(blocks)} blocks, {len(rows)} entries')
