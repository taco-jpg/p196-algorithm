#!/usr/bin/env python3
"""Untrusted generator (sprint agent 02) of the width-3 "method limit" certificate for the
forward invariant of Agent #124 (lean/P196/Agent124ForwardInvariant, set `Agent124.FwdW3.fset`).

It writes, under OUTDIR (= lean/P196/Sprint/Agent02):
  W3Data.lean   two code-keyed trees over the 4,194 words of fset:
                fromT  breadth-first tree from W0 = projection of orbit(196,100), value
                       depth*SH + parent*2 + carry  with forwardPrefix(parent, carry) = node
                toT    breadth-first tree towards W0, value depth*SH + next*2 + carry
                       with forwardPrefix(node, carry) = next
  W3Check.lean  kernel checks of both trees, key coverage of fset, the root predecessor U0
  W3Final.lean  the theorems (see that file)
Every fact is re-checked by kernel reduction; this script is not trusted.

Usage: gen_limit.py OUTDIR
"""
import os
import sys
from collections import deque
from itertools import product

SH = 1099511627776  # must equal Sprint.Agent02.SH


def T(n):
    return n + int(str(n)[::-1])


def pair_word(n):
    d = [int(c) for c in str(n)][::-1]
    L = len(d)
    return [d[i] + d[L - 1 - i] for i in range(L)]


def forward_prefix(s, inner):
    k = len(s)
    low, carry = [], 0
    for v in s:
        carry, d = divmod(v + carry, 10)
        low.append(d)
    high, c = [0] * k, inner
    for i in range(k - 1, -1, -1):
        c, high[i] = divmod(s[i] + c, 10)
    if c:
        return (1 + low[0],) + tuple(low[i] + high[i - 1] for i in range(1, k))
    return tuple(a + b for a, b in zip(low, high))


def word_code(w):
    a = 1
    for d in w:
        a = 19 * a + d
    return a


def tree_expr(items):
    """balanced BST over sorted (code, value) items"""
    def rec(lo, hi):
        if lo >= hi:
            return '.empty'
        mid = (lo + hi) // 2
        c, v = items[mid]
        return f'(.node {c} {v} {rec(lo, mid)} {rec(mid + 1, hi)})'
    return rec(0, len(items))


def main():
    out = sys.argv[1]
    k = 3
    n = 196
    for _ in range(100):
        n = T(n)
    assert n == 44757771534490515617290699271561508443627774644
    w0 = tuple(pair_word(n)[:k])
    # forward closure (identical to gen_fwd.py of Agent #124)
    F = {w0}
    st = [w0]
    while st:
        w = st.pop()
        for e in (0, 1):
            p = forward_prefix(w, e)
            if p not in F:
                F.add(p)
                st.append(p)
    assert len(F) == 4194
    # BFS from w0
    parent = {w0: (None, 0, 0)}
    dq = deque([w0])
    while dq:
        w = dq.popleft()
        d = parent[w][2]
        for e in (0, 1):
            p = forward_prefix(w, e)
            if p not in parent:
                parent[p] = (w, e, d + 1)
                dq.append(p)
    assert set(parent) == F
    # reverse BFS to w0
    rev = {w: [] for w in F}
    for w in F:
        for e in (0, 1):
            rev[forward_prefix(w, e)].append((w, e))
    nxt = {w0: (None, 0, 0)}
    dq = deque([w0])
    while dq:
        w = dq.popleft()
        d = nxt[w][2]
        for (u, e) in rev[w]:
            if u not in nxt:
                nxt[u] = (w, e, d + 1)
                dq.append(u)
    assert set(nxt) == F, 'fset is not strongly connected'
    # a predecessor of w0 inside F (closing a cycle through the root)
    preds0 = sorted(((parent[u][2], word_code(u), e) for (u, e) in rev[w0]))
    assert preds0
    _, U0, E0 = preds0[0]
    W0 = word_code(w0)
    for w in F:
        assert all(x < 19 for x in w) and w[0] > 0
    from_items = sorted((word_code(w), (parent[w][2] * SH + (word_code(parent[w][0]) * 2 + parent[w][1]
                                                              if parent[w][0] is not None else 0)))
                        for w in F)
    to_items = sorted((word_code(w), (nxt[w][2] * SH + (word_code(nxt[w][0]) * 2 + nxt[w][1]
                                                         if nxt[w][0] is not None else 0)))
                      for w in F)
    # digit words in F with positive lead: the 3-digit prefixes at the method limit
    limit = [w for w in product(range(10), repeat=k) if w[0] > 0 and w in F]
    print('fset', len(F), 'max from-depth', max(v[2] for v in parent.values()),
          'max to-depth', max(v[2] for v in nxt.values()), 'U0', U0, 'E0', E0, 'limit words', len(limit))
    hdr = ('/-! Generated by sprint/agent-02/src/gen_limit.py; untrusted data, kernel-checked use. -/\n')
    data = ('import P196.Sprint.Agent02.Core\n\n' + hdr +
            'namespace Sprint.Agent02.W3\nopen Agent124.CodeCert\n\n'
            f'/-- Code of the 3-column projection `[8, 8, 13]` of `orbit 196 100`. -/\ndef W0 : Nat := {W0}\n\n'
            f'/-- A listed predecessor of `W0` and its carry. -/\ndef U0 : Nat := {U0}\n\ndef E0 : Nat := {E0}\n\n'
            '/-- Breadth-first tree of `fset` from `W0`: value `depth * SH + parent * 2 + carry`. -/\n'
            f'def fromT : CodeTree := {tree_expr(from_items)}\n\n'
            '/-- Breadth-first tree of `fset` towards `W0`: value `depth * SH + next * 2 + carry`. -/\n'
            f'def toT : CodeTree := {tree_expr(to_items)}\n\nend Sprint.Agent02.W3\n')
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'W3Data.lean'), 'w') as f:
        f.write(data)
    print('W3Data.lean bytes', len(data))
    with open(os.path.join(out, 'W3-limit-words.txt'), 'w') as f:
        for w in limit:
            f.write(''.join(map(str, w)) + '\n')


if __name__ == '__main__':
    main()
