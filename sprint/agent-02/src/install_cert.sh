#!/usr/bin/env bash
# Regenerate a width-K rank certificate with Agent #124's archived gen_code4.py (copied in repro/)
# and install it under lean/P196/Sprint/Agent02 with this repository's import paths.
# The Short and Final modules of gen_code4.py are not installed: the 196 endpoint used here,
# Sprint.Agent02.no_196_of_entry_long, needs only the long rows (RowsClosed) and the entry check.
# Usage (from the repository root): install_cert.sh K PREFIX[,PREFIX...] TAG NAMESPACE_SUFFIX
#   install_cert.sh 8 2342 S2K8 CertK8
#   install_cert.sh 8 9149,6676 S2K8B CertK8B
set -euo pipefail
K=$1; P=$2; TAG=$3; NS=$4
OUT=$(mktemp -d)
python3 -I sprint/agent-02/repro/gen_code4.py "$K" "$OUT" "$P" --tag "$TAG"
for f in "$OUT"/*.lean; do
  b=$(basename "$f")
  case $b in *Short*|*Final*) continue;; esac
  sed -e 's/^import Agent124\(CodeCert\|CodeRange\|ShortSplit\|PrefixL\)$/import P196.Agent117P2641.Agent124\1/' \
      -e "s/^import \\(A124${TAG}[A-Za-z0-9]*\\)\$/import P196.Sprint.Agent02.\\1/" \
      -e "s/Agent124\\.Cert${TAG}/Sprint.Agent02.${NS}/g" \
      -e 's/Generated by gen_code.py (Agent #124)/Generated by gen_code4.py of Agent #124 (archive tag, run by sprint agent 02)/' \
      "$f" > "lean/P196/Sprint/Agent02/$b"
done
rm -rf "$OUT"
# one module per entry (each width-8 entry check needs about 5 GB)
python3 -I sprint/agent-02/src/split_entries.py "lean/P196/Sprint/Agent02/A124${TAG}Entries.lean"
