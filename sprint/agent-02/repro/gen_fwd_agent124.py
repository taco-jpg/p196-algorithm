#!/usr/bin/env python3
"""Untrusted generator of the forward-closed code-keyed set F_k for the 196
orbit (Agent #124) and the Lean modules that kernel-check it.

F_k = forward closure, under both inner-carry choices of the exact prefix map
(mirror of SevenColumnProjection.forwardPrefix), of the first k pair sums of
orbit(196, 100).  Every closure step is re-checked in Lean.

Usage: gen_fwd.py K OUTDIR [--leaf N] [--leaves-per-data M] [--leaves-per-rows R]
"""
import argparse
import hashlib
import json
import os
from itertools import product


def T(n):
    return n + int(str(n)[::-1])


def pair_word(n):
    d = [int(c) for c in str(n)][::-1]
    L = len(d)
    return [d[i] + d[L - 1 - i] for i in range(L)]


def forward_prefix(s, inner):
    k = len(s)
    low, carry = [], 0
    for v in s:
        carry, d = divmod(v + carry, 10)
        low.append(d)
    high, c = [0] * k, inner
    for i in range(k - 1, -1, -1):
        c, high[i] = divmod(s[i] + c, 10)
    if c:
        return (1 + low[0],) + tuple(low[i] + high[i - 1] for i in range(1, k))
    return tuple(a + b for a, b in zip(low, high))


def word_code(w):
    a = 1
    for d in w:
        a = 19 * a + d
    return a


HEADER = '''import {imports}

/-! Generated by gen_fwd.py (Agent #124); untrusted data, kernel-checked use. -/
namespace Agent124.{ns}
open Agent124.CodeCert
set_option maxRecDepth 100000
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('k', type=int)
    ap.add_argument('outdir')
    ap.add_argument('--leaf', type=int, default=1024)
    ap.add_argument('--leaves-per-data', type=int, default=8)
    ap.add_argument('--leaves-per-rows', type=int, default=4)
    ap.add_argument('--count-chunks', type=int, default=9)
    args = ap.parse_args()
    k = args.k
    tag = f'W{k}'
    ns = f'Fwd{tag}'
    mod = f'A124{tag}'
    os.makedirs(args.outdir, exist_ok=True)
    n = 196
    for _ in range(100):
        n = T(n)
    assert n == 44757771534490515617290699271561508443627774644
    w0 = tuple(pair_word(n)[:k])
    seen = {w0}
    stack = [w0]
    while stack:
        w = stack.pop()
        for inner in (0, 1):
            p = forward_prefix(w, inner)
            if p not in seen:
                seen.add(p)
                stack.append(p)
    items = sorted((word_code(w), w) for w in seen)
    codes = [c for c, _ in items]
    assert len(set(codes)) == len(codes)

    depth = 0
    while (len(items) >> depth) > args.leaf:
        depth += 1
    leaves, internal = [], []

    def expr(lo, hi):
        if lo >= hi:
            return '.empty'
        mid = (lo + hi) // 2
        return f'(.node {items[mid][0]} 0 {expr(lo, mid)} {expr(mid + 1, hi)})'

    def top(lo, hi, d):
        if lo >= hi:
            return '.empty', 'trivial'
        if d == depth:
            name = f'leaf{len(leaves):04d}'
            leaves.append((name, expr(lo, hi), hi - lo))
            return name, f'fwd_{name}'
        mid = (lo + hi) // 2
        idx = len(internal)
        internal.append(items[mid][0])
        le, lp = top(lo, mid, d + 1)
        re_, rp = top(mid + 1, hi, d + 1)
        return f'(.node {items[mid][0]} 0 {le} {re_})', f'⟨{lp}, fwd_branch{idx:04d}, {rp}⟩'

    top_expr, top_proof = top(0, len(items), 0)
    files = {}
    data_mods = []
    for i in range(0, len(leaves), args.leaves_per_data):
        name = f'{mod}Data{i // args.leaves_per_data:03d}'
        body = HEADER.format(imports='Agent124CodeCert', ns=ns)
        for lname, lexpr, cnt in leaves[i:i + args.leaves_per_data]:
            body += f'\n/-- {cnt} keys. -/\ndef {lname} : CodeTree := {lexpr}\n'
        body += f'\nend Agent124.{ns}\n'
        files[name] = body
        data_mods.append(name)
    tree_mod = f'{mod}Tree'
    body = HEADER.format(imports='\nimport '.join(data_mods), ns=ns)
    body += (f'\n/-- Forward closure of the first {k} pair sums of the 196 orbit at time 100: '
             f'{len(items)} words. -/\ndef fset : CodeTree := {top_expr}\n\nend Agent124.{ns}\n')
    files[tree_mod] = body
    row_mods = []
    for i in range(0, len(leaves), args.leaves_per_rows):
        name = f'{mod}Fwd{i // args.leaves_per_rows:03d}'
        body = HEADER.format(imports=f'{tree_mod}\nimport Agent124Forward', ns=ns)
        body += 'open Agent124.Forward\n'
        for lname, _, cnt in leaves[i:i + args.leaves_per_rows]:
            body += (f'\ntheorem fwd_{lname} : {lname}.All (fun c _ => fwdOK fset {k} c = true) :=\n'
                     f'  allFwd_sound (by decide +kernel)\n')
        body += f'\nend Agent124.{ns}\n'
        files[name] = body
        row_mods.append(name)
    br_mod = f'{mod}Branch'
    body = HEADER.format(imports=f'{tree_mod}\nimport Agent124Forward', ns=ns)
    body += 'open Agent124.Forward\n'
    for idx, code in enumerate(internal):
        body += (f'\ntheorem fwd_branch{idx:04d} : fwdOK fset {k} {code} = true := by\n'
                 f'  decide +kernel\n')
    body += f'\nend Agent124.{ns}\n'
    files[br_mod] = body
    # closure assembly, initial membership, endpoint
    fin_mod = f'{mod}Final'
    body = HEADER.format(imports='\nimport '.join(row_mods + [br_mod]), ns=ns)
    body += 'open Lychrel196 Agent124.Forward Agent124.PrefixL SevenColumn.Certificate SevenColumnProjection\n'
    body += (f'\nset_option maxHeartbeats 100000000 in\n'
             f'theorem closed : fset.All (fun c _ => fwdOK fset {k} c = true) :=\n  {top_proof}\n'
             f'\nset_option maxHeartbeats 0 in\n'
             f'theorem init : Mem fset (wordPrefix q100 {k}) := by\n'
             f'  show (lookupC fset (wordCode (wordPrefix q100 {k}))).isSome = true\n'
             f'  decide +kernel\n'
             f'\n/-- No state of the 196 orbit, at any time, is a palindrome beginning with a {k}-digit\n'
             f'word missing from `fset` (when a final overflow into it is impossible). -/\n'
             f'theorem no_196_outside_fset : ∀ T pre, pre.length = {k} → noOverflowPre pre = true →\n'
             f'    lookupC fset (wordCode pre) = none → ¬ PalStartsL pre (orbit 196 T) :=\n'
             f'  no_196_outside (by decide) (by decide) (by decide) closed init\n'
             f'\n#print axioms closed\n#print axioms init\n#print axioms no_196_outside_fset\n'
             f'end Agent124.{ns}\n')
    files[fin_mod] = body
    # explicit counts of excluded leading words, one module per leading digit
    digit_words = [w for w in product(range(10), repeat=k) if w[0] > 0]
    excluded = [w for w in digit_words if w not in seen]
    def nov(w):
        return w[0] >= 2 or any(x >= 3 for x in w)
    excl_nov = [w for w in excluded if nov(w)]
    cnt_mods, counts = [], {}
    for a in range(1, 10):
        name = f'{mod}Count{a}'
        c_a = sum(1 for w in excl_nov if w[0] == a)
        counts[a] = c_a
        body = HEADER.format(imports=f'{tree_mod}\nimport Agent124Forward', ns=ns)
        body += 'open Agent124.PrefixK Agent124.PrefixL SevenColumn.Certificate\n'
        body += (f'\n/-- Leading digit {a}: the {k}-digit words missing from `fset` with no possible final\n'
                 f'overflow. -/\ndef excluded{a} : List (List Nat) :=\n'
                 f'  ((digitLists {k - 1}).map ([{a}] ++ ·)).filter (fun w =>\n'
                 f'    noOverflowPre w && (lookupC fset (wordCode w)).isNone)\n'
                 f'\nset_option maxHeartbeats 0 in\n'
                 f'theorem excluded{a}_length : excluded{a}.length = {c_a} := by\n  decide +kernel\n'
                 f'\nend Agent124.{ns}\n')
        files[name] = body
        cnt_mods.append(name)
    sum_mod = f'{mod}Summary'
    body = HEADER.format(imports='\nimport '.join([fin_mod] + cnt_mods), ns=ns)
    body += 'open Lychrel196 Agent124.Forward Agent124.PrefixL SevenColumn.Certificate\n'
    nest = 'excluded9'
    for a in range(8, 0, -1):
        nest = f'excluded{a} ++ ({nest})'
    body += (f'\n/-- All excluded {k}-digit leading words, listed by leading digit. -/\n'
             f'def excluded : List (List Nat) := {nest}\n'
             f'\ntheorem excluded_length : excluded.length = {len(excl_nov)} := by\n'
             f'  simp only [excluded, List.length_append, ' + ', '.join(f'excluded{a}_length' for a in range(1, 10)) + ']\n'
             f'\n/-- The 196 orbit never contains a palindrome beginning with any listed word. -/\n'
             f'theorem no_196_excluded : ∀ T, ∀ w ∈ excluded, ¬ PalStartsL w (orbit 196 T) := by\n'
             f'  intro T w hw\n'
             f'  simp only [excluded, List.mem_append] at hw\n'
             f'  have h : w.length = {k} ∧ noOverflowPre w = true ∧ lookupC fset (wordCode w) = none := by\n'
             f'    rcases hw with ' + ' | '.join(['hw'] * 9) + '\n'
             f'    all_goals exact mem_excluded_props (by decide) hw\n'
             f'  exact no_196_outside_fset T w h.1 h.2.1 h.2.2\n'
             f'\n#print axioms excluded_length\n#print axioms no_196_excluded\nend Agent124.{ns}\n')
    files[sum_mod] = body

    for name, text in files.items():
        with open(os.path.join(args.outdir, name + '.lean'), 'w') as f:
            f.write(text)
    order = data_mods + [tree_mod, br_mod] + row_mods + [fin_mod] + cnt_mods + [sum_mod]
    meta = {'k': k, 'tag': tag, 'w0': list(w0), 'words': len(items), 'leaves': len(leaves),
            'internal': len(internal), 'digit_words_in_F': len(digit_words) - len(excluded),
            'excluded_digit_words': len(excluded), 'excluded_no_overflow': len(excl_nov),
            'excluded_by_leading_digit': counts, 'build_order': order,
            'sha256': {nm: hashlib.sha256(files[nm].encode()).hexdigest() for nm in order}}
    with open(os.path.join(args.outdir, f'{mod}-meta.json'), 'w') as f:
        json.dump(meta, f, indent=1)
    print(json.dumps({x: meta[x] for x in ('k', 'w0', 'words', 'leaves', 'digit_words_in_F',
                                            'excluded_digit_words', 'excluded_no_overflow')}))
    print(' '.join(order))


if __name__ == '__main__':
    main()
