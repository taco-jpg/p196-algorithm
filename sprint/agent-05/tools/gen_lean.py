"""Generate Lean witness modules from a max-delay table.

usage: python3 gen_lean.py TABLE.tsv MIN_DELAY LEAN_DIR MODULE [--chunk-size 20] [--title TEXT]

Writes LEAN_DIR/<MODULE>C00.lean, <MODULE>C01.lean, ... (one kernel check per
witness, at most chunk-size witnesses per file to keep kernel memory small) and
an aggregator LEAN_DIR/<MODULE>.lean with the list theorems.  Lean module path
prefix is P196.Sprint.Agent05.

Every witness (prefix, seed, t) with t > MIN_DELAY is first recomputed here
with Python big integers (orbit, palindrome, width, leading digits); the
Lean kernel re-checks it independently through `witnessOK`.
"""
import sys, os

def rev(x): return int(str(x)[::-1])

def recompute(pre, seed, t):
    x = seed
    for _ in range(t): x = x + rev(x)
    s = str(x)
    assert s == s[::-1], (pre, seed, t, "not a palindrome")
    assert s.startswith(pre), (pre, seed, t, s[:10])
    return x, len(s)

HDR = "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n"
OPEN = "open Lychrel196 Agent124.PrefixR Agent124.PrefixL Sprint.Agent05"

def chunk_file(ns, rows, src_note):
    defs, names = [], []
    for j, (pre, seed, t) in enumerate(rows):
        P, W = recompute(pre, seed, t)
        digs = ",".join(pre)
        defs.append(f"def w{j} : Witness := ⟨[{digs}], {seed}, {t},\n    {P}, {W}⟩\n"
                    f"theorem w{j}_ok : witnessOK w{j} = true := by decide +kernel\n")
        names.append(f"w{j}")
    return f"""import P196.Sprint.Agent05.DelayWitness

/-! Generated by sprint/agent-05/tools/gen_lean.py ({src_note}).
Untrusted data: each witness is re-checked by the kernel through `witnessOK`. -/

namespace {ns}
{OPEN}

{HDR}
{chr(10).join(defs)}
def witnesses : List Witness := [{", ".join(names)}]

theorem witnesses_ok : witnesses.all witnessOK = true := by
  simp only [witnesses, List.all_cons, List.all_nil, {", ".join(n + "_ok" for n in names)},
    Bool.and_true, Bool.true_and]

end {ns}

#print axioms {ns}.witnesses_ok
"""

def aggregator(ns, chunk_ns, n, mind, prefixes, title):
    imports = "\n".join(f"import P196.Sprint.Agent05.{c.split('.')[-1]}" for c in chunk_ns)
    cat = " ++ ".join(f"{c}.witnesses" for c in chunk_ns)
    oks = ", ".join(f"{c}.witnesses_ok" for c in chunk_ns)
    plist = ", ".join("[" + ",".join(p) + "]" for p in prefixes)
    return f"""{imports}

/-!
# {title}

Generated by sprint/agent-05/tools/gen_lean.py. {n} kernel-checked delay
witnesses, one per four-digit prefix{"" if mind < 0 else ", each with delay `t > " + str(mind) + "`"}.
`realized`: each is an actual positive seed whose orbit at time `t` is a
palindrome beginning with the prefix. `ancestry_bound_ge`: every uniform
ancestry bound for the prefix is at least `t`. `entry_bound_ge`: every
accepted Agent124 entry `(prefix, b)` has `t ≤ b + 1`. `not_mem_entries`:
with base check `N < t` no entry list passing the premises of
`no_196_of_entries` contains the prefix.
-/

namespace {ns}
{OPEN}

{HDR}
def witnesses : List Witness := {cat}

theorem witnesses_ok : witnesses.all witnessOK = true := by
  simp only [witnesses, List.all_append, {oks}, Bool.and_true, Bool.true_and]

/-- The listed prefixes, in order. -/
theorem prefixes : witnesses.map (·.pre) = [{plist}] := by rfl

theorem length_witnesses : witnesses.length = {n} := by rfl

{"" if mind < 0 else "theorem delays_gt : witnesses.all (fun w => Nat.blt " + str(mind) + " w.t) = true := by rfl" + chr(10)}
theorem realized : ∀ w ∈ witnesses, 0 < w.seed ∧ PalStartsL w.pre (orbit w.seed w.t) := by
  intro w hw
  exact witnessOK_sound w (List.all_eq_true.mp witnesses_ok w hw)

theorem ancestry_bound_ge : ∀ w ∈ witnesses, ∀ B, AncestryBound w.pre B → w.t ≤ B := by
  intro w hw B h
  obtain ⟨hA, hP⟩ := realized w hw
  exact le_of_witness h hA hP

theorem entry_bound_ge (k : Nat) (R : List Nat → Option Nat)
    (rows : RowsClosed k R) (short : ShortClosed k R) :
    ∀ w ∈ witnesses, ∀ b, entryOK k R (w.pre, b) = true → w.t ≤ b + 1 := by
  intro w hw b hok
  exact entry_bound_ge_of_witnessOK w (List.all_eq_true.mp witnesses_ok w hw)
    k R rows short b hok

theorem not_mem_entries (k : Nat) (R : List Nat → Option Nat)
    (rows : RowsClosed k R) (short : ShortClosed k R)
    (entries : List (List Nat × Nat)) (h : entries.all (entryOK k R) = true)
    (N : Nat) (hb : entries.all (fun e => Nat.ble (e.2 + 1) N) = true) :
    ∀ w ∈ witnesses, N < w.t → ∀ b, (w.pre, b) ∉ entries := by
  intro w hw ht
  exact not_mem_entries_of_witnessOK w (List.all_eq_true.mp witnesses_ok w hw)
    k R rows short entries h N hb ht

/-- The same for every shorter prefix (`j = 3`: the three-digit parent, `j = 2`: the
two-digit one). -/
theorem not_mem_entries_take (k : Nat) (R : List Nat → Option Nat)
    (rows : RowsClosed k R) (short : ShortClosed k R)
    (entries : List (List Nat × Nat)) (h : entries.all (entryOK k R) = true)
    (N : Nat) (hb : entries.all (fun e => Nat.ble (e.2 + 1) N) = true) :
    ∀ w ∈ witnesses, N < w.t → ∀ j b, (w.pre.take j, b) ∉ entries := by
  intro w hw ht j
  exact not_mem_entries_take_of_witnessOK w (List.all_eq_true.mp witnesses_ok w hw)
    k R rows short entries h N hb ht j

end {ns}

#print axioms {ns}.witnesses_ok
#print axioms {ns}.prefixes
#print axioms {ns}.length_witnesses
{"" if mind < 0 else "#print axioms " + ns + ".delays_gt" + chr(10)}#print axioms {ns}.realized
#print axioms {ns}.ancestry_bound_ge
#print axioms {ns}.entry_bound_ge
#print axioms {ns}.not_mem_entries
#print axioms {ns}.not_mem_entries_take
"""

def main():
    tsv, mind, ldir, mod = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    cs = int(sys.argv[sys.argv.index("--chunk-size") + 1]) if "--chunk-size" in sys.argv else 20
    title = sys.argv[sys.argv.index("--title") + 1] if "--title" in sys.argv else f"Delay witnesses with delay > {mind}"
    rows = []
    for line in open(tsv):
        if line.startswith("prefix"): continue
        pre, t, seed = line.split("\t")[:3]
        if int(t) > mind: rows.append((pre, int(seed), int(t)))
    rows.sort(key=lambda r: (-r[2], r[0]))
    chunk_ns = []
    for c in range(0, len(rows), cs):
        name = f"{mod}C{c // cs:02d}"
        ns = f"Sprint.Agent05.{name}"
        txt = chunk_file(ns, rows[c:c + cs], f"{os.path.basename(tsv)}, delay > {mind}, rows {c}..{min(c + cs, len(rows)) - 1}")
        open(os.path.join(ldir, name + ".lean"), "w").write(txt)
        chunk_ns.append(ns)
    agg = aggregator(f"Sprint.Agent05.{mod}", chunk_ns, len(rows), mind, [r[0] for r in rows], title)
    open(os.path.join(ldir, mod + ".lean"), "w").write(agg)
    print(f"{mod}: {len(rows)} witnesses in {len(chunk_ns)} chunk files", file=sys.stderr)

main()
