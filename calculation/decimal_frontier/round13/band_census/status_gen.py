#!/usr/bin/env python3
"""Regenerate FINAL_status.md (hand-curated text + lists built from the logs)."""
import re, glob, os, collections, sys
sys.path.insert(0,os.path.expanduser('~/p196_run/r13a'))
ROOT=os.path.expanduser('~/p196_run/r13a')
res=collections.defaultdict(list)
for d in glob.glob(ROOT+'/logs/*'):
    if not os.path.isdir(d): continue
    for f in glob.glob(d+'/i*.log'):
        for line in open(f):
            if not line.startswith('BANDRESULT'): continue
            m=re.match(r'BANDRESULT (\S+) b=(\d+) clock=(\d+) V=([\d,]+) T=(\d+) epochs=(\d+)(?: Tprime=(\d+))? tau=(\d+) R=(\d+) Rfree=(\d+) solver=(\w+) enc=(\d) : rots=(\S+) status=(\w+)',line)
            if not m: continue
            mode,b,clk,V,T,M,TP,tau,R,Rf,solver,enc,rots,st=m.groups()
            res[(mode,b,clk,V,int(T),int(M),int(TP) if TP else int(T)*int(M),int(tau),int(R))].append((st,rots,solver,enc))
out=[]
out.append('## 0b. Status summary (generated by status_gen.py; hand-written context in FINAL_head; last run see date below)')
def lst(mode_prefix,clk,cond):
    L=sorted(k for k,v in res.items() if k[0].startswith(mode_prefix) and k[2]==clk and cond(k,v))
    return L
for clk in ['1000','10','00001110001']:
    allu=sorted(set((k[3],k[0],k[4],k[6],k[7],k[8]) for k,v in res.items() if k[2]==clk and any(x[0]=='ALLUNSAT' for x in v)))
    out.append(f'\n**Clock {clk}: bands with an ALLUNSAT result** (V, mode, T, horizon T\', origin tau, R; methods listed in sec. 7 explicit list):')
    if allu:
        byV=collections.defaultdict(list)
        for V,mode,T,TP,tau,R in allu: byV[(V,T)].append(f'{mode}:T\'={TP}'+(f',tau={tau}' if tau else '')+(f',R={R}' if R!=12 else ''))
        out.append('; '.join(f'({V}) T={T} [{", ".join(ms)}]' for (V,T),ms in sorted(byV.items(),key=lambda kv:(len(kv[0][0].split(',')),kv[0][1],kv[0][0]))))
    else:
        out.append('(none yet)')
open(ROOT+'/FINAL_status_auto.md','w').write('\n'.join(out)+'\n')
print('\n'.join(out)[:3000])

import bandsat as BS
def selfmirror(V, clk, T, b=10):
    p=len(clk); x=list(V); n=len(V)
    def palneck(w):
        r=w[::-1]
        return any(all(w[(i+k)%n]==r[i] for i in range(n)) for k in range(n))
    ok=True
    for t in range(T):
        if t%p==0 and not palneck(x): ok=False
        x,*_=BS.rowstep(x,int(clk[t%p]),b)
    return ok

# survivors: bands tested in L(M=1,tau=0) with PASS and with no ALLUNSAT in any mode (L, L*, Lr, R, R*) -- candidate list so far
import mkjobs as MK
out2=['\n**Survivors so far** = bands whose L(M=1, tau=0) result is PASS and with NO ALLUNSAT in any applicable test (L, L*, Lr, tau-scans, and R, R* except for self-mirror bands, whose centre can be the fold) up to now; the list is the current "candidate" set of the census (a pass is only a necessary test).  Bands with timeouts count as UNDECIDED, not survivors.']
for clk,title in [('1000','clock 1000'),('10','clock 10'),('00001110001','clock p11')]:
    bands=MK.parse(clk,8)
    surv=[]
    for B in bands:
        V=B['V']
        keysL=[k for k in res if k[2]==clk and k[3]==V]
        if not keysL: continue
        l1=[v for k,v in res.items() if k[0]=='L' and k[2]==clk and k[3]==V and k[5]==1 and k[7]==0 and k[8]==12]
        if not l1: continue
        st1=[x[0] for v in l1 for x in v]
        if 'PASS' not in st1: continue
        allu=False
        for k in keysL:
            if not any(x[0]=='ALLUNSAT' for x in res[k]): continue
            # R/R* exclusions do not apply to self-mirror bands (their centre can be the fold)
            if k[0] in ('R','R*') and selfmirror([int(x) for x in V.split(',')],clk,B['T']): continue
            allu=True
        if allu: continue
        # R status known?
        rr=[x[0] for k,v in res.items() if k[0]=='R' and k[2]==clk and k[3]==V for x in v]
        rs=[x[0] for k,v in res.items() if k[0]=='R*' and k[2]==clk and k[3]==V for x in v]
        tag=('SM ' if selfmirror([int(x) for x in V.split(',')],clk,B['T']) else '')+('R:'+('PASS' if 'PASS' in rr else ('UNDEC' if rr else '-')))+(' R*:'+('PASS' if 'PASS' in rs else ('ALLUNSAT' if 'ALLUNSAT' in rs else ('UNDEC' if rs else '-'))))
        surv.append((B['s'],B['T'],V,tag))
    surv.sort()
    out2.append(f'\n{title}: {len(surv)} survivors: '+'; '.join(f'({V}) s={s} T={T} [{tag}]' for s,T,V,tag in surv[:80])+(' ...' if len(surv)>80 else ''))
with open(ROOT+'/FINAL_status_auto.md','a') as f:
    f.write('\n'.join(out2)+'\n')

# ALLUNSAT entries lacking a second method
missing=[]
for k,v in res.items():
    if not any(x[0]=='ALLUNSAT' for x in v): continue
    combos=set((x[2],x[3]) for x in v if x[0]=='ALLUNSAT')
    if len(combos)<2:
        missing.append((k,sorted(combos)))
with open(ROOT+'/FINAL_status_auto.md','a') as f:
    f.write('\n**ALLUNSAT entries with only one solver/encoding so far (cross-checks pending):** '+str(len(missing))+'\n')
    for k,c in sorted(missing)[:60]:
        f.write(f'- {k[0]} clock={k[2]} V={k[3]} T={k[4]} M={k[5]} T\'={k[6]} tau={k[7]} R={k[8]}: {c}\n')
print('missing cross-check:',len(missing))

# D-type (exact period, free-port relaxation) summary: bands with LD PASS at some m
outD=['\n**D-type results (LD, exact-period junction in the free-port relaxation, R=12; not a necessary condition for all periods, only for the tested period mT):**']
for clk in ['1000','10','00001110001']:
    dpass={}
    for k,v in res.items():
        if k[0]=='LD' and k[2]==clk:
            V=k[3]; dpass.setdefault(V,[]).append((k[5],v[0][0],v[0][1],k[4]))
    if not dpass: continue
    sat=[(V,sorted((m,st,rots) for m,st,rots,t in lst_)) for V,lst_ in dpass.items() if any(st=='PASS' for m,st,rots,t in lst_)]
    outD.append(f'clock {clk}: {len(dpass)} bands tested; {len(sat)} with an exact-period junction (LD SAT for some rotation at m=1 or 2):')
    outD.append('; '.join(f'({V}) '+' '.join(f'm={m}:{rots}' for m,st,rots in lst_ if st=="PASS") for V,lst_ in sorted(sat,key=lambda x:(len(x[0].split(",")),x[0]))))
with open(ROOT+'/FINAL_status_auto.md','a') as f:
    f.write('\n'.join(outD)+'\n')
