#!/usr/bin/env python3
"""Standalone independent replay of agent-712's complete p29/m7 periodic bulk graph.

Reconstructs the full functional-graph SCC/cycle classification from a temporary
CSV map generated by the C++ exhaustive census. Independently checks all
recurrent rows by exact decimal cyclic-carry arithmetic and large-integer
one-step interior pairword normalization; verifies modulo-nine charges.

No reachability, centre, or Lychrel conclusion is made.
"""
import collections
import re
import sys
from pathlib import Path

BASE=10
M=7
G='00001110001000110001000110001'
Q=19**4


def row(j):
    a=j%19;b=j//19%19;c=j//361%19;d=j//6859%19
    return (a,b,c,d,d,c,b)


def cyclic_carries(r, ascending):
    n=len(r)
    solutions=[]
    for guess in (0,1):
        c=[None]*n
        c[0]=guess
        if ascending:
            for i in range(n-1):
                c[i+1]=(r[i]+c[i])//BASE
            valid=((r[-1]+c[-1])//BASE==guess)
        else:
            c[-1]=(r[0]+c[0])//BASE
            for i in range(n-1,1,-1):
                c[i-1]=(r[i]+c[i])//BASE
            valid=((r[1]+c[1])//BASE==guess)
        if valid:
            solutions.append(tuple(c))
    return solutions


def row_step(r,gamma):
    if all(x==BASE-1 for x in r):
        raise ValueError('neutral row')
    up=cyclic_carries(r,True)
    down=cyclic_carries(r,False)
    assert len(up)==len(down)==1,(r,up,down)
    a,d=up[0],down[0]
    e=[(r[i]+a[i])%BASE for i in range(M)]
    f=[(r[i]+d[i])%BASE for i in range(M)]
    return tuple(e[i]+f[(i-gamma)%M] for i in range(M)),a,d


def primitive(r):
    return 1 if len(set(r))==1 else 7


def bigint_check(r):
    """Check a genuine 701-digit INTEGER normalization at 500 interior positions.

    It is a one-step local bulk check, not a decimal certificate: gamma comes
    from the actual length growth of this specially constructed pairword.
    """
    if not r[0] or r[0]==9:
        return False
    n=701
    pair=[r[i%M] for i in range(n)]
    assert pair==pair[::-1]
    amount=sum(x*10**i for i,x in enumerate(pair))
    digits=list(map(int,str(amount)[::-1]))
    gamma=len(digits)-n
    assert gamma in (0,1)
    nextrow,_,_=row_step(r,gamma)
    assert all(digits[i]+digits[-1-i]==nextrow[i%M] for i in range(100,600)),r
    return True


def graph_cycle_data(mapping):
    indeg=[0]*Q
    for m in mapping:
        if m>=0:
            indeg[m]+=1
    q=collections.deque(i for i,v in enumerate(indeg) if v==0)
    while q:
        i=q.popleft();j=mapping[i]
        if j>=0:
            indeg[j]-=1
            if indeg[j]==0:
                q.append(j)
    visited=set();cycles=[]
    for i in range(Q):
        if indeg[i]>0 and i not in visited:
            cycle=[];j=i
            while j not in visited:
                visited.add(j);cycle.append(j);j=mapping[j]
            assert j==i
            cycles.append(cycle)
    return cycles


def main():
    summary=Path(sys.argv[1]).read_text()
    mapping=list(map(int,Path(sys.argv[2]).read_text().split()))
    assert len(mapping)==Q and all(-1<=j<Q for j in mapping)
    assert mapping.count(-1)==1
    cycles=graph_cycle_data(mapping)
    hist=collections.Counter((primitive(row(c[0])),len(c)) for c in cycles)
    assert hist=={(1,1):2,(1,2):1,(1,6):1,(7,2):3,(7,6):2,(7,24):1,(7,26):1},hist
    assert len(cycles)==11 and sum(map(len,cycles))==78
    assert sum(len(c) for c in cycles if primitive(row(c[0]))==7)==68
    cxx_reps=[]
    for line in summary.splitlines():
        if line.startswith('CYCLE '):
            length=int(re.search(r'length=(\d+)',line).group(1))
            r=tuple(map(int,re.search(r'representative=([\d,]+)',line).group(1).rstrip(',').split(',')))
            cxx_reps.append((r,length))
    assert len(cxx_reps)==11
    assert all(any(r in [row(j) for j in cyc] and len(cyc)==length for cyc in cycles)
               for r,length in cxx_reps)
    charge_hist=collections.Counter()
    checked=0
    bigint_checks=0
    for cyc in cycles:
        period=203*len(cyc)
        r0=row(cyc[0]);r=r0
        assert period%29==0
        full=period*(3 if period%6 else 1)
        charge=[0]*M
        for t in range(full):
            gamma=int(G[t%29]);nxt,a,d=row_step(r,gamma)
            if t<period and (t+1)%203==0:
                assert nxt==row(cyc[((t+1)//203)%len(cyc)]),(t,r,nxt)
            for k in range(M):
                h=(r[k]+d[k])//BASE
                yy=(r[(k-1)%M]+d[(k-1)%M])%BASE
                charge[k]=(charge[k]+pow(5,t,9)*(a[k]-h+gamma*yy))%9
            r=nxt
            if t+1==period:
                assert r==r0
        assert r==r0
        assert len(set(charge))==1,charge
        charge_hist[(primitive(r0),charge[0])]+=1
        checked+=period
        for j in cyc:
            bigint_checks+=int(bigint_check(row(j)))
        print('CONTROL cycle period=',period,'primitive=',primitive(r0),'charge=',charge[0], 'start=',r0)
    assert charge_hist[(7,0)]==5 and charge_hist[(7,3)]==1 and charge_hist[(7,6)]==1,charge_hist
    assert bigint_checks>=60,bigint_checks
    assert 'starts=130321 dead=1 valid=130320 wrong=0 map_agreement=130321 complete_cycles=11 primitive_cycles=7 recurrent_nodes=78 primitive_recurrent_nodes=68' in summary
    print('PASS exhaustive map',Q,'two independently computed transitions per state')
    print('PASS independent graph',len(cycles),'cycles and',sum(map(len,cycles)),'recurrent vertices')
    print('PASS exact recurrence',checked,'true temporal steps; big-integer normalized pairword checks',bigint_checks)
    print('PASS charge histogram',dict(charge_hist))

if __name__=='__main__': main()
