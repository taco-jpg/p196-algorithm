#!/usr/bin/env python3
"""Independent bounded controls for the scientific exterior MDD checker.

No full P24 closure audit is run here. Forward block tables are generated by
choosing the old low-carry word, old partner digit, initial coefficient and the
entire new high-carry word before computing either block symbol. This differs
from target-conditioned inverse generation. Small arbitrary set certificates
are also compared with the independent literal column oracle.
"""
from __future__ import annotations

import argparse
import itertools
import json
import random
import time

import p24_reverse_certificate as certificate
import p24_reverse_controls as literal


def partition(g):
    positions = [t for t, gt in enumerate(g) if gt]
    return [{"start": start, "length": (positions[(j + 1) % len(positions)] - start - 1) % len(g) + 1}
            for j, start in enumerate(positions)]


def encode(g, cut):
    low, high, lag = cut
    answer = []
    for index, block in enumerate(partition(g)):
        start, length = block["start"], block["length"]
        l = sum(((low >> ((start + j) % len(g))) & 1) << j for j in range(length))
        h = sum(((high >> ((start + j) % len(g))) & 1) << j for j in range(length))
        answer.append(l | (h << length) | (lag[index] << (2 * length)))
    return tuple(answer)


def decode(g, labels):
    low = high = 0
    lag = []
    for block, label in zip(partition(g), labels):
        start, length = block["start"], block["length"]
        for j in range(length):
            phase = (start + j) % len(g)
            low |= ((label >> j) & 1) << phase
            high |= ((label >> (length + j)) & 1) << phase
        lag.append(label >> (2 * length))
    return low, high, tuple(lag)


def diagram(base, e, g, states):
    """Plain prefix tree; deliberately no canonical interning or hash sharing."""
    n = sum(g)
    nodes = [{"level": 0, "arcs": []}, {"level": n, "arcs": []}]

    def build(level, words):
        if not words:
            return 0
        if level == n:
            return 1
        groups = {}
        for word in words:
            groups.setdefault(word[level], []).append(word)
        arcs = [[label, build(level + 1, group)] for label, group in sorted(groups.items())]
        nodes.append({"level": level, "arcs": arcs})
        return len(nodes) - 1

    root = build(0, sorted({encode(g, state) for state in states}))
    return {"base": base, "e": "".join(map(str, e)), "g": "".join(map(str, g)),
            "blocks": partition(g), "root": root, "nodes": nodes}


def forward_tiles(base, length, budget):
    """Complete old-L/old-Y/initial-x/new-H enumeration, without a target."""
    answers = [set() for _ in range(base << (2 * length))]
    for old_low in range(1 << length):
        for old_lag in range(base):
            for initial in range(2 * base - 1):
                for new_high in range(1 << length):
                    budget.tick()
                    x, old_high, new_low = initial, 0, 0
                    column = []
                    for j in range(length):
                        column.append(x)
                        old_high_bit, reverse_digit = divmod(x + ((new_high >> j) & 1), base)
                        new_low_bit, forward_digit = divmod(x + ((old_low >> j) & 1), base)
                        old_high |= old_high_bit << j
                        new_low |= new_low_bit << j
                        if j == 0:
                            new_lag = reverse_digit
                        x = forward_digit + (old_lag if j == 0 else reverse_digit)
                    source = old_low | (old_high << length) | (old_lag << (2 * length))
                    target = new_low | (new_high << length) | (new_lag << (2 * length))
                    answers[target].add((initial, x, source, tuple(column)))
    literal.require(sum(map(len, answers)) == base * (2 * base - 1) * (4 ** length),
                    "forward tile census lost a unique complete choice")
    return answers


def tile_controls(budget):
    target_count = tile_count = 0
    details = []
    for base, lengths in ((2, range(1, 7)), (3, range(1, 4)),
                          (4, (1, 2)), (10, (1, 3, 4))):
        for length in lengths:
            e, g = (0,) * length, (1,) + (0,) * (length - 1)
            checker = certificate.Checker(diagram(base, e, g, ()), budget)
            expected = forward_tiles(base, length, budget)
            for target, tiles in enumerate(expected):
                actual = checker.local_tiles(length, target)
                literal.require(len(actual) == len(set(actual)), "duplicate checker block tile")
                literal.require(set(actual) == tiles, "complete forward block table mismatch")
                target_count += 1
                tile_count += len(actual)
            details.append({"base": base, "length": length, "targets": len(expected),
                            "tiles": sum(map(len, expected))})
    return {"complete_block_targets": target_count, "complete_block_tiles": tile_count,
            "block_censuses": details}


def literal_first(base, g):
    """Trace a finite cyclic coefficient graph before retaining any cut."""
    values = range(1, 2 * base - 1)
    arcs = []
    for gt in g:
        row = {}
        for x in values:
            edges = []
            for q in (0, 1):
                h, r = divmod(x + q, base)
                if h == gt:
                    xn = x % base + (1 if gt else r)
                    if xn in values:
                        edges.append((xn, (x // base, q, r if gt else -1)))
            row[x] = edges
        arcs.append(row)
    cuts = {}
    for initial in values:
        viable = [set() for _ in range(len(g) + 1)]
        viable[-1].add(initial)
        for t in range(len(g) - 1, -1, -1):
            viable[t] = {x for x in values if any(xn in viable[t + 1] for xn, _ in arcs[t][x])}

        def walk(t, x, labels, column):
            if t == len(g):
                literal.require(x == initial, "open FIRST trajectory")
                cuts.setdefault(literal.pack(g, labels), tuple(column))
                return
            for xn, label in arcs[t][x]:
                if xn in viable[t + 1]:
                    walk(t + 1, xn, labels + [label], column + [x])

        if initial in viable[0]:
            walk(0, initial, [], [])
    return cuts


def first_and_known_path_controls(budget, fixtures):
    specs = {(base, tuple(g)) for base, _, g, _, _, _ in fixtures}
    specs.add((10, literal.bits(literal.P24_G)))
    for base, maximum in ((2, 4), (3, 3), (10, 4)):
        for length in range(1, maximum + 1):
            specs.update((base, g) for g in itertools.product((0, 1), repeat=length) if any(g))
    first_states = 0
    for base, g in sorted(specs):
        e = (0,) * len(g)
        checker = certificate.Checker(diagram(base, e, g, ()), budget)
        expected = literal_first(base, g)
        actual = checker.first()
        actual_states = {decode(g, labels) for labels in actual}
        literal.require(actual_states == set(expected), "complete FIRST frontier mismatch")
        root, _ = literal.root_and_terminal(base, e, g)
        for labels, column in actual.items():
            literal.check_column(base, g, root, decode(g, labels), column, first=True)
        first_states += len(actual)
    path_tiles = terminal_checks = 0
    for base, e, g, rows, cuts, columns in fixtures:
        checker = certificate.Checker(diagram(base, e, g, (cuts[-1],)), budget)
        literal.require(checker.terminal() == encode(g, cuts[-1]), "terminal symbol mismatch")
        literal.require(checker.contains(encode(g, cuts[-1])), "literal terminal not included")
        terminal_checks += 1
        for j, column in enumerate(columns):
            source, target = encode(g, cuts[j]), encode(g, cuts[j + 1])
            for index, block in enumerate(partition(g)):
                start, length = block["start"], block["length"]
                values = tuple(column[(start + k) % len(g)] for k in range(length))
                end = column[(start + length) % len(g)]
                expected_tile = values[0], end, source[index], values
                literal.require(expected_tile in checker.local_tiles(length, target[index]),
                                "known complete-word path missing a block tile")
                path_tiles += 1
    return {"complete_first_drivers": len(specs), "complete_first_states": first_states,
            "known_path_block_memberships": path_tiles, "known_terminal_encodings": terminal_checks}


def replay_violation(base, g, members, witness, initial):
    target_labels, source_labels, column = [], [], [None] * len(g)
    for block, (target, source, values) in zip(partition(g), witness):
        target_labels.append(target)
        source_labels.append(source)
        literal.require(len(values) == block["length"], "counterexample block width")
        for j, value in enumerate(values):
            column[(block["start"] + j) % len(g)] = value
    target, source = decode(g, target_labels), decode(g, source_labels)
    literal.require(target in members and source not in members, "wrong closure counterexample endpoints")
    literal.require(column[partition(g)[0]["start"]] == initial, "wrong initial cyclic port")
    literal.check_column(base, g, source, target, column)


def closure_controls(budget):
    rng = random.Random(110240705)
    drivers = sets_checked = closed = violations = preimage_states = 0
    for base, periods in ((2, (2, 3)), (3, (2,))):
        for period in periods:
            for g in itertools.product((0, 1), repeat=period):
                if not any(g):
                    continue
                e = tuple(rng.randrange(2) for _ in g)
                universe = [(low, high, lag) for low in range(1 << period)
                            for high in range(1 << period)
                            for lag in itertools.product(range(base), repeat=sum(g))]
                inverse = {target: set(literal.inverse_columns(base, g, target)) for target in universe}
                preimage_states += sum(map(len, inverse.values()))
                samples = [set(), set(universe)]
                samples += [{universe[index]} for index in (0, len(universe) // 2, len(universe) - 1)]
                for threshold in (0.05, 0.15, 0.3, 0.5, 0.7, 0.9):
                    samples.append({row for row in universe if rng.random() < threshold})
                seed = {universe[rng.randrange(len(universe))]}
                while True:
                    enlarged = seed | set().union(*(inverse[row] for row in seed))
                    if enlarged == seed:
                        break
                    seed = enlarged
                samples.append(seed)
                distinct = {frozenset(sample) for sample in samples}
                for frozen in distinct:
                    budget.tick()
                    members = set(frozen)
                    predecessors = set().union(*(inverse[row] for row in members))
                    expected_bad = predecessors - members
                    checker = certificate.Checker(diagram(base, e, g, members), budget)
                    found = None
                    for initial in range(2 * base - 1):
                        witness = checker.counterexample(checker.root, checker.root, initial, initial)
                        if witness is not None:
                            replay_violation(base, g, members, witness, initial)
                            found = witness
                            break
                    literal.require((found is not None) == bool(expected_bad),
                                    "small-set predecessor closure decision mismatch")
                    sets_checked += 1
                    closed += not expected_bad
                    violations += bool(expected_bad)
                drivers += 1
    return {"explicit_closure_drivers": drivers, "explicit_sets_checked": sets_checked,
            "explicit_closed_sets": closed, "explicit_violation_witnesses_replayed": violations,
            "small_inverse_edges": preimage_states}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seconds", type=int, default=120)
    args = parser.parse_args()
    literal.require(1 <= args.seconds <= 1500, "invalid control budget")
    budget = certificate.Budget(seconds=args.seconds, operations=100_000_000, memory_mib=1024)
    _, fixtures = literal.baseline_controls()
    result = tile_controls(budget)
    result.update(first_and_known_path_controls(budget, fixtures))
    result.update(closure_controls(budget))
    result.update(status="PASS", seconds=time.monotonic() - budget.start, operations=budget.operations)
    print(json.dumps(result, sort_keys=True), flush=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (certificate.Incomplete, ValueError, TypeError, AssertionError, MemoryError) as error:
        print(json.dumps({"status": "UNDECIDED", "reason": str(error)}), flush=True)
        raise SystemExit(2)
