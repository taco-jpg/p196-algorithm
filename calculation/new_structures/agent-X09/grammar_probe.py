#!/usr/bin/env python3
"""LZ78 and entropy probe for the genuine 196 pair-coefficient halfwords.
Inputs are generated by orbit.cpp; no template dynamics are assumed.
"""
import hashlib, json, math, pathlib, random, zlib
from collections import Counter
ROOT=pathlib.Path(__file__).resolve().parent
TIMES=[10000,20000,40000,80000,100000]
def read(out,t):
    lines=(out/f't{t}.txt').read_text().splitlines()
    d,p=lines[1:3]
    assert len(d)==len(p) and p==p[::-1]
    return d,p[:len(p)//2]
def lz78(s):
    tree=[{}];i=0;ph=[]
    while i<len(s):
        q=0;start=i
        while i<len(s) and s[i] in tree[q]:
            q=tree[q][s[i]];i+=1
        if i<len(s):
            tree[q][s[i]]=len(tree);tree.append({});i+=1
        ph.append(i-start)
    return dict(phrases=len(ph),maximum=max(ph),mean=round(sum(ph)/len(ph),5))
def entropy(s,k):
    freq=Counter(s[j:j+k] for j in range(len(s)-k+1))
    n=sum(freq.values())
    return round(-sum((v/n)*math.log2(v/n) for v in freq.values()),5)
def profile(s):
    return dict(lz78=lz78(s),gzip_ratio=round(len(zlib.compress(s.encode(),9))/len(s),5),H1=entropy(s,1),H2=entropy(s,2),H3=entropy(s,3),H4=entropy(s,4))
def main(out):
    results=[]
    for t in TIMES:
        d,p=read(out,t);r=random.Random(109+t)
        z=list(p);r.shuffle(z)
        result=dict(t=t,digits=len(d),halfword=len(p),native=profile(p),frequency_shuffle=profile(''.join(z)))
        if t==100000:result['decimal_sha256']=hashlib.sha256(d.encode()).hexdigest()
        results.append(result)
    d,_=read(out,2000)
    # An independent arbitrary-precision integer replay (separate arithmetic).
    n=196
    for t in range(2000):n+=int(str(n)[::-1])
    assert str(n)==d,'independent Python integer replay mismatch at t=2000'
    print(json.dumps({'label':'COMPUTED','orbit':'decimal 196', 'max_iteration':100000,
                      'palindromes':0,'integer_replay_control':2000,'profiles':results},indent=2))
if __name__=='__main__':
    import sys
    main(pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else ROOT/'scratch')
