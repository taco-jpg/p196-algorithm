#!/usr/bin/env python3
"""Exact independent audit of W01's four third-pulse-spacing decimal emission ports.

All trace CSVs are regenerated by C++ literal digit-vector arithmetic before this
script runs. The reference XY two-body trace is regenerated separately.
"""
import csv
import sys
from pathlib import Path

ZS=(9920,10000,10080,10160)
if len(sys.argv)!=6:
    raise SystemExit('usage: param_verify.py four triple CSVs in Z order, then pair CSV')

def load(file):
    with open(file,newline='') as f:
        return {int(r['t']):r for r in csv.DictReader(f)}

D={z:load(p) for z,p in zip(ZS,sys.argv[1:5])}
P=load(sys.argv[5])
assert len(P)==18251 and (min(P),max(P))==(1750,20000)
expected={}
with Path(__file__).with_name('param_expected.csv').open(newline='') as f:
    for r in csv.DictReader(f):expected[int(r['k'])]=r
assert set(expected)=={-1,0,1,2}

for z in ZS:
    R=D[z];k=(z-10000)//80
    assert len(R)==18501 and (min(R),max(R))==(1500,20000),z
    first=next((t,int(r['front'])) for t,r in R.items() if int(r['front'])>=0)
    assert first==(4354+88*k,9014+60*k),(z,first)
    assert int(expected[k]['z'])==z
    assert first==(int(expected[k]['birth_t']),int(expected[k]['birth_front']))
    assert int(R[20000]['shield_gap'])==int(expected[k]['final_gap'])
    assert all(len(r['low'])==len(r['high'])==122 for r in R.values())

aligned=gap_differences=0
for z in (9920,10080,10160):
    k=(z-10000)//80
    for t in range(5300,min(20000,20000-88*k)+1):
        a,b=D[10000][t],D[z][t+88*k]
        assert int(b['front'])==int(a['front'])+60*k,(z,t,'front')
        assert (b['low'],b['high'])==(a['low'],a['high']),(z,t,'emission')
        gap_differences+=a['shield_gap']!=b['shield_gap']
        aligned+=1
    # Mutations: neither a wrong one-cell displacement nor a wrong time phase works.
    a,b=D[10000][6000],D[z][6000+88*k]
    assert int(b['front'])!=int(a['front'])+60*k+1
    c=D[z][6000+88*k-1]
    assert (c['low'],c['high'])!=(a['low'],a['high'])
assert aligned==43839 and gap_differences==43839,(aligned,gap_differences)

period44=shields=antipodal=nonzero_kinks=0
alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
seam_states=[]
for z in ZS:
    k=(z-10000)//80
    R=D[z]
    for t in range(5300,19957):
        a,b=R[t],R[t+44]
        assert int(b['front'])==int(a['front'])-10,(z,t,'44front')
        assert (b['low'],b['high'])==(a['low'],a['high']),(z,t,'44tile')
        period44+=1
    for t in range(5300,20001):
        a,b=R[t],P[t]
        assert int(a['shield_gap'])>=41,(z,t,'shield')
        shields+=1
        assert int(a['front'])==int(b['front'])+2000+80*k,(z,t,'XYfront')
        low=[];high=[]
        for side,array in (('low',low),('high',high)):
            for j in range(61):
                v=int(a[side][j*2:j*2+2],16)-36
                w=alphabet.index(b[side][j])-18
                array.append(v+w)
        assert not any(low[:56]) and not any(high[:56]),(z,t,'antipodal56')
        assert any(low[56:]) or any(high[56:]),(z,t,'nonzero_seam')
        antipodal+=112
        nonzero_kinks+=1
        if z==10000:seam_states.append((t,tuple(low[56:]+high[56:])))
assert period44==58628 and shields==58804 and antipodal==6586048
assert nonzero_kinks==58804
E=dict(seam_states)
assert len(set(E.values()))==44
assert all(E[t]==E[t+44] for t in range(5300,19957))
assert any(E[t]!=E[t+22] for t in range(5300,19979))
print('W01_PARAM_PORT_PASS four_Z_cases=4 real_orbits=32 steps=20000 '
      f'aligned_rows={aligned} signed_aligned_equalities={aligned*122} '
      f'port_44_rows={period44} signed_44_equalities={period44*122} '
      f'shield_rows={shields} antipodal_digit_checks={antipodal} '
      'distinct_seam_states=44 period=44 first_birth=(4266,8954) '
      f'nonperiodic_gap_comparisons={gap_differences}')
