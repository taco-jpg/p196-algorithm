"""Rank replay using literal integer arithmetic instead of quotient.step.

The finite rank certificate is checked, not regenerated by a graph traversal.
All-width interpretation still depends on the written quotient theorem.
"""
from __future__ import annotations
import argparse
import base64
import gzip
import hashlib
import json
import time
from collections import Counter
from math import comb
from pathlib import Path
from quotient import State, Edge, states


def literal_step(s: State, g: int = 3, h: int = 5) -> Edge:
    """Extract raw interfaces from the literal integer output at fixed test gaps."""
    c,d=s.c,18-s.c
    source=s.B+(c,)*g+s.A+(d,)*h+s.C+(d,)*h+s.A[::-1]+(c,)*g+s.B[::-1]
    # Separate canonical realization; string reversal implements ordinary R(n).
    ds=[0]*len(source)
    for i in range(len(source)//2):
        ds[i]=min(9,source[i])
        ds[-1-i]=source[i]-ds[i]
    if source[0]<=9:
        ds[0]=source[0]-1
        ds[-1]=1
    if len(source)%2:
        ds[len(source)//2]=source[len(source)//2]//2
    n=int(''.join(map(str,ds[::-1])))
    output=str(n+int(str(n)[::-1]))
    D=tuple(map(int,output[::-1]))
    actual=tuple(D[i]+D[-1-i] for i in range(len(D)))
    gamma=len(D)-len(source)
    assert gamma in (0,1)
    assert output!=output[::-1]
    cp=2*(c if c<9 else c-9)
    dp=18-cp
    br=len(s.B)+1
    ar=len(s.A)+2-gamma
    cr=len(s.C)+2-gamma
    rg,rh=g-2+gamma,h-2+gamma
    p=br
    B=actual[:p]
    assert actual[p:p+rg]==(cp,)*rg
    p+=rg
    A=actual[p:p+ar];p+=ar
    assert actual[p:p+rh]==(dp,)*rh
    p+=rh
    C=actual[p:p+cr]
    assert actual==B+(cp,)*rg+A+(dp,)*rh+C+(dp,)*rh+A[::-1]+(cp,)*rg+B[::-1]
    # Independent index-based trimming, not the producer's repeated slicing.
    endB=len(B)
    while endB>0 and B[endB-1]==cp:
        endB-=1
    startA=0
    while startA<len(A) and A[startA]==cp:
        startA+=1
    endA=len(A)
    while endA>startA and A[endA-1]==dp:
        endA-=1
    startC=0
    while startC<len(C)//2 and C[startC]==dp:
        startC+=1
    assert C==C[::-1]
    t=State(cp,B[:endB],A[startA:endA],C[startC:len(C)-startC])
    t.validate(trimmed=True)
    dg=len(B)-endB+startA-2+gamma
    dh=len(A)-endA+startC-2+gamma
    assert t.word(g+dg,h+dh)==actual
    return Edge(t,dg,dh,gamma)


def count_size(i: int) -> int:
    """Coefficient of 8(1+10z)(1-z^2)^5/(1-19z^2)^3."""
    k=i//2
    a=sum((-1)**j*comb(5,j)*comb(k-j+2,2)*19**(k-j) for j in range(min(5,k)+1))
    return 8*a*(10 if i%2 else 1)


def replay(cap: int, folder: Path) -> dict:
    started=time.monotonic()
    summary=json.loads((folder/f'cap{cap}-summary.json').read_text())
    archive=folder/f'cap{cap}-ranks.json.gz'
    packed=archive.read_bytes() if archive.exists() else base64.b64decode(
        Path(str(archive)+'.b64').read_text(), validate=False)
    assert hashlib.sha256(packed).hexdigest()==summary['rank_archive_sha256']
    raw=gzip.decompress(packed)
    assert hashlib.sha256(raw).hexdigest()==summary['rank_json_sha256']
    ranks=json.loads(raw)
    vertices=list(states(cap))
    rank_of=dict(zip(vertices,ranks))
    assert len(ranks)==len(vertices)==len(rank_of)==sum(count_size(i) for i in range(cap+1))
    assert len(vertices)==summary['vertices']
    assert min(ranks)>=1 and max(ranks)==summary['max_exit_transitions']
    counts=Counter(s.interface_size for s in vertices)
    assert all(counts[i]==count_size(i)==summary[f'I={i}'] for i in range(cap+1))
    digest=hashlib.sha256()
    edgecount=exitcount=0
    for s,r in zip(vertices,ranks):
        e=literal_step(s)
        if e.target.interface_size<=cap:
            assert r==rank_of[e.target]+1
            edgecount+=1
        else:
            assert r==1
            exitcount+=1
        encode=lambda s:[s.c,list(s.B),list(s.A),list(s.C)]
        record=[encode(s),encode(e.target),e.dg,e.dh,e.overflow]
        digest.update((json.dumps(record,separators=(',',':'))+'\n').encode())
    assert edgecount==summary['edges'] and exitcount==summary['exits']
    assert digest.hexdigest()==summary['edge_stream_sha256']
    result={'status':'PASS','cap':cap,'literal_integer_edge_checks':len(vertices),
            'independent_rank_checks':len(vertices),'internal_edges':edgecount,
            'exits':exitcount,'max_exit_transitions':max(ranks),
            'edge_stream_sha256':digest.hexdigest(),
            'elapsed_seconds':round(time.monotonic()-started,4),
            'scope':'Finite rank replay, not Lean verification or global cycle exclusion.'}
    (folder/f'cap{cap}-replay.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2),flush=True)
    return result

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cap',type=int,default=6)
    p.add_argument('--results',type=Path,default=Path('results'))
    args=p.parse_args()
    replay(args.cap,args.results)
