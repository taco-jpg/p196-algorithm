#!/usr/bin/env python3
"""Recover two truncated stored probe artifacts from their exact parent graph.

Requires regenerated bytes to match the pre-existing producer SHA-256.
The failed byte strings are preserved as evidence. This does not expand
the capped search or change any mathematical output.
"""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import tempfile

HERE = Path(__file__).resolve().parent


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


def main():
    scalar = module("scalar_clock", HERE / "scalar_clock.py")
    reader = module("finite_bound", HERE.parent / "2026-10-14-broader-return" / "finite_bound.py")
    directory = HERE / "seven_1"
    report = json.loads((directory / "scalar_clock.json").read_text())
    recovery = HERE / "recovery"
    recovery.mkdir(exist_ok=True)
    records = []
    for width in (8, 11):
        expected = report["completed_graphs"][width - 1]["raw_artifact"]
        target = directory / expected["filename"]
        previous = report["completed_graphs"][width - 2]["retained_artifact"]
        parent = directory / previous["filename"]
        assert hashlib.sha256(parent.read_bytes()).hexdigest() == previous["sha256"]
        failed = recovery / (target.name + ".truncated")
        if hashlib.sha256(target.read_bytes()).hexdigest() != expected["sha256"]:
            if failed.exists():
                if target.read_bytes() != failed.read_bytes():
                    extra = recovery / (target.name + ".truncated." + hashlib.sha256(target.read_bytes()).hexdigest()[:12])
                    extra.write_bytes(target.read_bytes())
            else:
                failed.write_bytes(target.read_bytes())
        w, vertices, edges = reader.read_graph(parent)
        assert w == width - 1
        graph = scalar.LIFT.empty(w)
        for row in vertices:
            for key, value in zip(("phase", "last", "low", "parent"), row):
                graph[key].append(value)
        for row in edges:
            for key, value in zip(("source", "target", "label"), row):
                graph[key].append(value)
        scalar.LIFT.CLOCK = tuple(report["overflow_clock"])
        with tempfile.TemporaryDirectory(prefix="p196-scalar-recovery-") as stage:
            scalar.LIFT.HERE = Path(stage)
            restored = scalar.LIFT.save(scalar.LIFT.lift(graph), "raw")
            assert restored == expected
            data = (Path(stage) / expected["filename"]).read_bytes()
        temporary = target.with_suffix(target.suffix + ".atomic-tmp")
        with temporary.open("wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
        records.append(dict(width=width, preserved_failed_file=str(failed.relative_to(HERE)),
                            failed_bytes=failed.stat().st_size,
                            failed_sha256=hashlib.sha256(failed.read_bytes()).hexdigest(),
                            restored=restored, parent=previous))
    (recovery / "report.json").write_text(json.dumps(dict(
        status="RESTORED_EXACT_ORIGINAL_HASHES", records=records,
        scope="Two files were found truncated after the producer run. Cause undetermined. Streaming rewrites did not persist reliably across calls; staged complete-byte writes and atomic replacement reproduced the original hashes and passed a subsequent-call verification. Recovery changes no result or search cap."), indent=2) + "\n")
    print("RESTORED_EXACT_ORIGINAL_HASHES")


if __name__ == "__main__":
    main()
