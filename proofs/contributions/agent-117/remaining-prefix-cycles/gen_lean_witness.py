#!/usr/bin/env python3
"""Emit a Lean 4 witness module for one CYCLE record (long states only).
usage: gen_lean_witness.py IN.jsonl PREFIX OUT_DIR"""
import sys, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import prefix_cycles as pc

def carry_for(s, p):
    """boundary carry e with forwardPrefix s e = p (the first that works)."""
    k = len(s)
    low, c = [], 0
    for v in s:
        c, d = divmod(v + c, 10); low.append(d)
    for e in (0, 1):
        high, c = [0] * k, e
        for i in range(k - 1, -1, -1):
            c, high[i] = divmod(s[i] + c, 10)
        q = (1 + low[0],) + tuple(low[i] + high[i - 1] for i in range(1, k)) if c else tuple(a + b for a, b in zip(low, high))
        if q == tuple(p):
            return e
    raise ValueError('no forward edge %s -> %s' % (s, p))

def pack(w, c):
    """base-19 little-endian packing of the k pair sums, carry in the low bit."""
    n = 0
    for v in reversed(w):
        n = n * 19 + v
    return n * 2 + c

def lean_list(words, carries):
    return '[' + ', '.join(str(pack(w, c)) for w, c in zip(words, carries)) + ']'

def emit(rec, out_dir):
    k = rec['k']; prefix = rec['prefix']
    entry = [tuple(w) for w in rec['entry_path']]
    cyc = [tuple(w) for w in rec['cycle']]
    assert cyc[0] == cyc[-1] and len(cyc) >= 2
    assert all(len(w) == k for w in entry + cyc), 'witness must use long states only'
    walk = entry + cyc               # p0 ... z, z ... z
    # carries: for each consecutive (p, s): e with forwardPrefix s e = p; stored with s
    carries_walk = [0] + [carry_for(walk[i + 1], walk[i]) for i in range(len(walk) - 1)]
    ne = len(entry)                  # entry words p0..p_{ne-1}, then z = cyc[0]
    entry_pairs = list(zip(walk[1:ne + 1], carries_walk[1:ne + 1]))     # after (p0,0): words p1..z
    cycle_pairs = list(zip(walk[ne + 1:], carries_walk[ne + 1:]))        # after (z, ez): words ... z
    ez = carries_walk[ne]
    name = 'Cycle%s_k%d' % (prefix, k)
    p0 = walk[0]; z = cyc[0]
    src = f'''import PrefixCycle

/-! Witness for prefix {prefix}, k = {k}: the backward closure of the initial row
`{list(p0)}` under `SevenColumn.prefixPredecessors` contains a cycle of length
{len(cyc) - 1} through `{list(z)}`, reached after {ne} backward steps.
Generated by gen_lean_witness.py; every edge is checked by kernel evaluation of
`SevenColumnProjection.forwardPrefix`. Method-limit statement only. -/

namespace Agent117.{name}

open SevenColumn SevenColumn.Certificate Agent117

def p0 : List Nat := [{', '.join(map(str, p0))}]
def z : List Nat := [{', '.join(map(str, z))}]
/-- Packed rows: base-19 little-endian pair sums with the forward carry in the low bit. -/
def entryData : List Nat := {lean_list([w for w, _ in entry_pairs], [c for _, c in entry_pairs])}
def cycleData : List Nat := {lean_list([w for w, _ in cycle_pairs], [c for _, c in cycle_pairs])}
def entry : List (List Nat × Nat) := entryData.map (unpack {k})
def cycle : List (List Nat × Nat) := cycleData.map (unpack {k})

theorem entry_ok : walkOK ((p0, 0) :: entry) = true := by decide +kernel
theorem entry_end : (entry.getLastD (p0, 0)).1 = z := by decide +kernel
theorem cycle_ok : walkOK ((z, {ez}) :: cycle) = true := by decide +kernel
theorem cycle_end : (cycle.getLastD (z, {ez})).1 = z := by decide +kernel
theorem cycle_pos : 0 < cycle.length := by decide +kernel

/-- No rank tree whose rows are all checked against the executable inverse
contains the initial row `p0` of prefix {prefix}; hence no certificate of the
seven-column kind bounds the ancestry of this row at k = {k}. -/
theorem no_checked_tree_contains_p0 (tree : RankTree)
    (checked : CheckedRows tree prefixPredecessors) : lookup tree p0 = none :=
  lookup_none_of_walks checked entry cycle p0 z 0 {ez} entry_ok entry_end cycle_ok cycle_end cycle_pos

theorem checkInitial_fails (tree : RankTree)
    (checked : CheckedRows tree prefixPredecessors) (bound : Nat) :
    checkInitial tree bound p0 = false := by
  unfold checkInitial; rw [no_checked_tree_contains_p0 tree checked]

#print axioms no_checked_tree_contains_p0
#print axioms checkInitial_fails

end Agent117.{name}
'''
    path = pathlib.Path(out_dir) / (name + '.lean')
    path.write_text(src)
    return path, ne, len(cyc) - 1

if __name__ == '__main__':
    fn, prefix, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
    for line in open(fn):
        rec = json.loads(line)
        if rec['prefix'] == prefix and rec['status'] == 'CYCLE':
            print(emit(rec, out_dir))
            break
