#!/usr/bin/env python3
"""Agent #117 adaptation of Agent #124 generator (upstream blob 95877d0668b1805cf0d348d34e429bf176ce715d).
Untrusted generator of combined width-k code-keyed prefix rank certificates
and the Lean modules that kernel-check them (Agent #124).

The generator, its ranks and its tree layout are NOT trusted: every row,
short transition and initial word is re-checked in Lean by kernel reduction
against the executable inverse `fastLongPred k` and `Agent124.PrefixK`.

Usage:
  gen_2641_code_cert.py 7 OUTDIR 2641 [--leaf N] [--leaves-per-data M]
              [--leaves-per-rows R] [--tag T]
"""
import argparse
import hashlib
import json
import os
import sys
from collections import defaultdict
from itertools import product

sys.setrecursionlimit(1000000)
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from legacy_prefix_cycles import Pred  # noqa: E402

# This file reads untrusted finite rows. An actual Lean kernel must verify them.
K_REQUIRED = 7
PREFIX_REQUIRED = (2, 6, 4, 1)
RANK_TABLE = os.path.join(HERE, "rank_rows_k7_2641.tsv")

def read_published_rank_table(path=RANK_TABLE):
    rows = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            word_text, rank_text = line.rstrip("\n").split("\t")
            w = tuple(int(a) for a in word_text.split(","))
            r = int(rank_text)
            if len(w) != K_REQUIRED or not 1 <= w[0] <= 18 or any(not 0 <= x <= 18 for x in w):
                raise ValueError(f"invalid row: {w}")
            if w in rows or not 0 <= r <= 5:
                raise ValueError(f"duplicate or invalid rank: {w}: {r}")
            rows[w] = r
    if len(rows) != 25624:
        raise ValueError(f"unexpected table size: {len(rows)}")
    roots = {(2, 6, 4, 1, a, b, c) for a in range(10) for b in range(10) for c in range(10)}
    if any(w not in rows or rows[w] > 5 for w in roots):
        raise ValueError("missing initial row or rank > 5")
    return rows


def word_code(w):
    a = 1
    for d in w:
        a = 19 * a + d
    return a


def closure(prefixes, k):
    if k != K_REQUIRED or prefixes != [PREFIX_REQUIRED]:
        raise ValueError("this adapter is ONLY for k=7 and prefix 2641")
    return read_published_rank_table(), {PREFIX_REQUIRED: 5}


class Builder:
    """Balanced BST over (code, word), top levels explicit, leaves named."""

    def __init__(self, items, leaf_target):
        self.items = items  # sorted by code
        n = len(items)
        depth = 0
        while (n >> depth) > leaf_target:
            depth += 1
        self.depth = depth
        self.leaves = []      # list of (name, lean_expr, count)
        self.internal = []    # list of (code, word, rank)
        self.ranges = []      # item index range of each leaf

    def expr(self, lo, hi):
        if lo >= hi:
            return '.empty'
        mid = (lo + hi) // 2
        code, w, r = self.items[mid]
        return f'(.node {code} {r} {self.expr(lo, mid)} {self.expr(mid + 1, hi)})'

    def top(self, lo, hi, d):
        """Returns Lean expr for the top structure and the matching proof term."""
        if lo >= hi:
            return '.empty', 'trivial'
        if d == self.depth:
            name = f'leaf{len(self.leaves):04d}'
            self.leaves.append((name, self.expr(lo, hi), hi - lo))
            self.ranges.append((lo, hi))
            return name, f'rows_{name}'
        mid = (lo + hi) // 2
        code, w, r = self.items[mid]
        idx = len(self.internal)
        self.internal.append((code, w, r))
        le, lp = self.top(lo, mid, d + 1)
        re_, rp = self.top(mid + 1, hi, d + 1)
        return (f'(.node {code} {r} {le} {re_})',
                f'⟨{lp}, row_branch{idx:04d}, {rp}⟩')


HEADER = '''import {imports}

/-! Generated by gen_code.py (Agent #124); untrusted data, kernel-checked use. -/
namespace Agent124.{ns}
open Agent124.CodeCert
set_option maxRecDepth 100000
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('k', type=int)
    ap.add_argument('outdir')
    ap.add_argument('prefixes')
    ap.add_argument('--leaf', type=int, default=256)
    ap.add_argument('--leaves-per-data', type=int, default=8)
    ap.add_argument('--leaves-per-rows', type=int, default=2)
    ap.add_argument('--tag', default=None)
    ap.add_argument('--budget', type=float, default=600.0)
    args = ap.parse_args()
    k = args.k
    tag = args.tag or '117P2641K7'
    ns = f'Cert{tag}'
    mod = f'A124{tag}'
    os.makedirs(args.outdir, exist_ok=True)
    prefixes = [tuple(int(c) for c in p) for p in args.prefixes.split(',')]
    height, bounds = closure(prefixes, k)
    items = sorted((word_code(w), w, r) for w, r in height.items())
    pred = Pred(k, cache=False)
    npred = {}
    for code, w, r in items:
        npred[code] = len(pred.preds(w)) if len(w) == k else 0
    codes = [c for c, _, _ in items]
    assert len(set(codes)) == len(codes)
    b = Builder(items, args.leaf)
    top_expr, top_proof = b.top(0, len(items), 0)

    files = {}
    # data modules
    data_mods = []
    for i in range(0, len(b.leaves), args.leaves_per_data):
        name = f'{mod}Data{i // args.leaves_per_data:03d}'
        imports = 'Agent124CodeCert'
        body = HEADER.format(imports=imports, ns=ns)
        for lname, lexpr, cnt in b.leaves[i:i + args.leaves_per_data]:
            body += f'\n/-- {cnt} nodes. -/\ndef {lname} : CodeTree := {lexpr}\n'
        body += f'\nend Agent124.{ns}\n'
        files[name] = body
        data_mods.append(name)
    tree_mod = f'{mod}Tree'
    body = HEADER.format(imports='\nimport '.join(data_mods), ns=ns)
    body += f'\n/-- Combined width-{k} code-keyed rank tree: {len(items)} nodes. -/\ndef ranks : CodeTree := {top_expr}\n'
    body += f'\nend Agent124.{ns}\n'
    files[tree_mod] = body

    # row chunk modules (heavy leaves split into key ranges)
    BUDGET = args.budget
    def cost(i0, i1):
        return sum(npred[items[i][0]] for i in range(i0, i1)) + 0.2 * (i1 - i0)
    row_mods = []
    split_report = []
    for i in range(0, len(b.leaves), args.leaves_per_rows):
        name = f'{mod}Rows{i // args.leaves_per_rows:03d}'
        group = list(range(i, min(i + args.leaves_per_rows, len(b.leaves))))
        heavy = [j for j in group if cost(*b.ranges[j]) > BUDGET]
        imports = f'{tree_mod}' + ('\nimport Agent124CodeRange' if heavy else '')
        body = HEADER.format(imports=imports, ns=ns)
        if heavy:
            body += 'open Agent124.CodeRange\n'
        for j in group:
            lname, _, cnt = b.leaves[j]
            lo, hi = b.ranges[j]
            if j not in heavy:
                body += (f'\ntheorem rows_{lname} : {lname}.All (fun c r => rowOK ranks {k} c r = true) :=\n'
                         f'  allRowsC_sound (by decide +kernel)\n')
                continue
            # split [lo,hi) into consecutive chunks with cost <= BUDGET
            chunks, start, acc = [], lo, 0.0
            for idx in range(lo, hi):
                c_i = npred[items[idx][0]] + 0.2
                if idx > start and acc + c_i > BUDGET:
                    chunks.append((start, idx)); start, acc = idx, 0.0
                acc += c_i
            chunks.append((start, hi))
            kb = [0] + [items[a][0] for a, _ in chunks[1:]] + [None]
            split_report.append({'leaf': lname, 'cost': cost(lo, hi), 'chunks': len(chunks)})
            for m in range(len(chunks)):
                blo = kb[m]
                bhi = 'none' if kb[m + 1] is None else f'(some {kb[m + 1]})'
                body += (f'\ntheorem rows_{lname}_part{m} : {lname}.All (fun c r => InRange {blo} {bhi} c → rowOK ranks {k} c r = true) :=\n'
                         f'  allRowsRange_sound (by decide +kernel)\n')
            proof = f'rows_{lname}_part{len(chunks) - 1}'
            for m in range(len(chunks) - 2, -1, -1):
                proof = f'all_join rows_{lname}_part{m} ({proof})'
            body += (f'\ntheorem rows_{lname} : {lname}.All (fun c r => rowOK ranks {k} c r = true) :=\n'
                     f'  all_full ({proof})\n')
        body += f'\nend Agent124.{ns}\n'
        files[name] = body
        row_mods.append(name)
    # internal rows
    br_mod = f'{mod}Branch'
    body = HEADER.format(imports=f'{tree_mod}', ns=ns)
    for idx, (code, w, r) in enumerate(b.internal):
        body += (f'\ntheorem row_branch{idx:04d} : rowOK ranks {k} {code} {r} = true := by\n'
                 f'  decide +kernel\n')
    body += f'\nend Agent124.{ns}\n'
    files[br_mod] = body
    # assembly
    all_mod = f'{mod}AllRows'
    imports = '\nimport '.join(row_mods + [br_mod])
    body = HEADER.format(imports=imports, ns=ns)
    body += 'open Agent124.PrefixR\n'
    body += (f'\nset_option maxHeartbeats 100000000\n'
             f'theorem allRowsAll : ranks.All (fun c r => rowOK ranks {k} c r = true) :=\n  {top_proof}\n'
             f'\ntheorem allRows : RowsClosed {k} (R ranks) := rowsClosed_of_all (by decide) allRowsAll\n'
             f'\n#print axioms allRows\nend Agent124.{ns}\n')
    files[all_mod] = body
    # short descent (widths >= 5 split into nineteen chunks by leading half entry)
    short_mod = f'{mod}Short'
    split_from = 5
    body = HEADER.format(imports=f'{tree_mod}' + ('\nimport Agent124ShortSplit' if k > split_from else ''), ns=ns)
    body += 'open Agent124.PrefixK Agent124.PrefixR\n'
    if k > split_from:
        body += 'open Agent124.ShortSplit\n'
    for n in range(0, k):
        if n < split_from:
            body += (f'\ntheorem short_w{n} : (symWords {n}).all (shortOKC ranks) = true := by\n'
                     f'  decide +kernel\n')
        else:
            for a in range(19):
                body += (f'\ntheorem short_w{n}_a{a:02d} : (symChunk {n} {a}).all (shortOKC ranks) = true := by\n'
                         f'  decide +kernel\n')
            body += (f'\ntheorem short_w{n} : (symWords {n}).all (shortOKC ranks) = true :=\n'
                     f'  all_symWords_of_chunks (by decide) fun a ha => by\n'
                     f'    have : ' + ' ∨ '.join(f'a = {a}' for a in range(19)) + ' := by omega\n'
                     f'    rcases this with ' + ' | '.join(['rfl'] * 19) + '\n')
            for a in range(19):
                body += f'    · exact short_w{n}_a{a:02d}\n'
    body += f'\ntheorem short : ShortClosed {k} (R ranks) := shortClosed_of_widths fun n hn => by\n'
    body += '  have : ' + ' ∨ '.join(f'n = {n}' for n in range(k)) + ' := by omega\n'
    body += '  rcases this with ' + ' | '.join(['rfl'] * k) + '\n'
    for n in range(k):
        body += f'  · exact short_w{n}\n'
    body += f'\n#print axioms short\nend Agent124.{ns}\n'
    files[short_mod] = body

    # Four-digit initial family, via Agent124.PrefixL rather than 3-digit PrefixK.
    init_mod = f'{mod}Initial'
    body = HEADER.format(imports=f'{tree_mod}\nimport Agent124PrefixL', ns=ns)
    body += 'open Agent124.PrefixL\n'
    body += (f'\ntheorem init_2641 : entryOK {k} (R ranks) ([2,6,4,1], 5) = true := by\n'
             f'  decide +kernel\n')
    body += f'\nend Agent124.{ns}\n'
    files[init_mod] = body

    # These candidate endpoints are NOT claimed Lean-checked by this generator.
    fin_mod = f'{mod}Final'
    body = HEADER.format(imports=f'{all_mod}\nimport {short_mod}\nimport {init_mod}', ns=ns)
    body += 'open Lychrel196 Agent124.PrefixL Agent124.PrefixR\n'
    body += (f'\ntheorem ancestry_2641 : ∀ A P t, 0 < A → '
             f'PalStartsL [2,6,4,1] P → orbit A t = P → t ≤ 6 := by\n'
             f'  have hi : [([2,6,4,1], 5)].all (entryOK {k} (R ranks)) = true := by\n'
             f'    simpa using init_2641\n'
             f'  exact ancestry_of_entries {k} (R ranks) allRows short '
             f'[([2,6,4,1],5)] hi ([2,6,4,1],5) (by simp)\n'
             f'\ntheorem no_196_2641 : ∀ t, '
             f'¬ PalStartsL [2,6,4,1] (orbit 196 t) := by\n'
             f'  have hi : [([2,6,4,1], 5)].all (entryOK {k} (R ranks)) = true := by\n'
             f'    simpa using init_2641\n'
             f'  have hb : [([2,6,4,1], 5)].all '
             f'(fun e => Nat.ble (e.2 + 1) 100) = true := by decide\n'
             f'  exact fun t => no_196_of_entries {k} (R ranks) allRows short '
             f'[([2,6,4,1],5)] hi hb t ([2,6,4,1],5) (by simp)\n'
             f'#print axioms ancestry_2641\n'
             f'#print axioms no_196_2641\n')
    body += f'\nend Agent124.{ns}\n'
    files[fin_mod] = body

    for name, text in files.items():
        with open(os.path.join(args.outdir, name + '.lean'), 'w') as f:
            f.write(text)
    order = data_mods + [tree_mod, br_mod] + row_mods + [all_mod, short_mod, init_mod, fin_mod]
    meta = {
        'k': k, 'tag': tag, 'prefixes': [''.join(map(str, p)) for p in prefixes],
        'nodes': len(items), 'max_rank': max(r for _, _, r in items),
        'bounds_ancestry': {''.join(map(str, p)): bounds[p] + 1 for p in prefixes},
        'leaves': len(b.leaves), 'internal': len(b.internal), 'depth': b.depth,
        'leaf_sizes': [cnt for _, _, cnt in b.leaves],
        'leaf_costs': [cost(*rg) for rg in b.ranges],
        'split_leaves': split_report, 'budget': BUDGET,
        'build_order': order,
        'sha256': {n: hashlib.sha256(files[n].encode()).hexdigest() for n in order},
    }
    with open(os.path.join(args.outdir, f'{mod}-meta.json'), 'w') as f:
        json.dump(meta, f, indent=1)
    print(json.dumps({x: meta[x] for x in ('k', 'nodes', 'max_rank', 'leaves', 'internal', 'depth', 'bounds_ancestry')}))
    print(' '.join(order))


if __name__ == '__main__':
    main()
