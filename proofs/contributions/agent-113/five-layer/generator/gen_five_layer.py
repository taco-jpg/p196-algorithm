#!/usr/bin/env python3
"""Generate the five-layer certificate (Agent #113). Untrusted: the Lean kernel
re-checks every closure row. Semantics mirror Agent113.FourColumn.Cert4.Checked:
  layer 0     = {(s0,0,s2,0) : s0 in {10,12,14,16}, s2 in {0,10,12,14,16}}
  layer r + 1 = {w in box : exists e in {0,1}, nextQ w e in layer r}
  box         = {(s0,s1,s2,s3) : 1 <= s0 <= 18, s1, s2, s3 <= 18}
Layers 0..h-1 are listed; layer h is the first empty one (h = 5).
Python standard library only.
"""
import itertools, json, sys

def hc3(s3, e): return (s3 + e) // 10
def hc2(s2, s3, e): return (s2 + hc3(s3, e)) // 10
def hc1(s1, s2, s3, e): return (s1 + hc2(s2, s3, e)) // 10
def top4(s0, s1, s2, s3, e): return (s0 + hc1(s1, s2, s3, e)) // 10
def lc1(s0): return s0 // 10
def lc2(s0, s1): return (s1 + lc1(s0)) // 10
def lc3(s0, s1, s2): return (s2 + lc2(s0, s1)) // 10

def next_quad(s0, s1, s2, s3, e):
    if top4(s0, s1, s2, s3, e) == 0:
        return (s0 % 10 + (s0 + hc1(s1, s2, s3, e)) % 10,
                (s1 + lc1(s0)) % 10 + (s1 + hc2(s2, s3, e)) % 10,
                (s2 + lc2(s0, s1)) % 10 + (s2 + hc3(s3, e)) % 10,
                (s3 + lc3(s0, s1, s2)) % 10 + (s3 + e) % 10)
    return (s0 % 10 + 1,
            (s1 + lc1(s0)) % 10 + (s0 + hc1(s1, s2, s3, e)) % 10,
            (s2 + lc2(s0, s1)) % 10 + (s1 + hc2(s2, s3, e)) % 10,
            (s3 + lc3(s0, s1, s2)) % 10 + (s2 + hc3(s3, e)) % 10)

EVEN = (0, 10, 12, 14, 16)
BOX = [w for w in itertools.product(range(1, 19), range(19), range(19), range(19))]

def layers():
    S = [sorted((a, 0, c, 0) for a in (10, 12, 14, 16) for c in EVEN)]
    while True:
        cur = set(S[-1])
        nxt = sorted(set(w for w in BOX for e in (0, 1) if next_quad(*w, e) in cur))
        if not nxt:
            return S
        S.append(nxt)

def T(n): return n + int(str(n)[::-1])
def quad4(m): return (m % 10 + m // 1000 % 10, m // 10 % 10 + m // 100 % 10,
                      m // 100 % 10 + m // 10 % 10, m // 1000 % 10 + m % 10)

def short_ok(S):
    for m in range(1, 1000):
        s = T(m)
        if s < 1000: continue
        assert s < 10000
        for lay in S:
            if quad4(s) in set(lay): return False
    return True

def lq(lay): return "[" + ", ".join(f"({a}, {b}, {c}, {d})" for a, b, c, d in lay) + "]"

def main(out):
    S = layers()
    h = len(S)
    assert [len(x) for x in S] == [20, 20, 18, 17, 5], [len(x) for x in S]
    assert short_ok(S)
    data = f"""import FourColumnChain

/-! Generated by generator/gen_five_layer.py (Agent #113). Untrusted data:
every closure row is checked by the Lean kernel in `FiveLayerRows*`. -/

namespace Agent113.FiveLayer

open Agent113.FourColumn

def cert5 : Cert4 where
  layers := [{(","+chr(10)+"    ").join(lq(l) for l in S)}]

theorem cert5_short : cert5.shortCheck = true := by decide +kernel

end Agent113.FiveLayer
"""
    open(f"{out}/FiveLayerData.lean", "w").write(data)
    for r in range(h):
        for a in range(1, 19):
            lines = [f"theorem r{r}_{a}_{b} : cert5.stepRow {r} {a} {b} = true := by decide +kernel"
                     for b in range(19)]
            row = (f"theorem r{r}_{a} : ∀ b, b ≤ 18 → cert5.stepRow {r} {a} b = true :=\n  cover19 " +
                   " ".join(f"r{r}_{a}_{b}" for b in range(19)))
            src = f"""import FiveLayerData

/-! Generated (Agent #113): kernel checks of closure rows (layer {r}, s0 = {a}). -/

namespace Agent113.FiveLayer

open Agent113.FourColumn

{chr(10).join(lines)}

{row}

end Agent113.FiveLayer
"""
            open(f"{out}/FiveLayerR{r}A{a}.lean", "w").write(src)
        imports = "\n".join(f"import FiveLayerR{r}A{a}" for a in range(1, 19))
        full = (f"theorem rows{r} : ∀ a, 1 ≤ a → a ≤ 18 → ∀ b, b ≤ 18 → cert5.stepRow {r} a b = true :=\n"
                f"  cover18 (P := fun a => ∀ b, b ≤ 18 → cert5.stepRow {r} a b = true) " +
                " ".join(f"r{r}_{a}" for a in range(1, 19)))
        src = f"""{imports}

/-! Generated (Agent #113): all closure rows of layer {r}. -/

namespace Agent113.FiveLayer

open Agent113.FourColumn

{full}

end Agent113.FiveLayer
"""
        open(f"{out}/FiveLayerRows{r}.lean", "w").write(src)
    json.dump({"layer_sizes": [len(x) for x in S], "layers": S, "h": h},
              open(f"{out}/generator/five_layer_certificate.json", "w"), indent=1)
    print("layers", [len(x) for x in S], "h", h)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
