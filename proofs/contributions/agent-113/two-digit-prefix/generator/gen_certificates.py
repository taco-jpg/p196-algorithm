#!/usr/bin/env python3
"""Generate the thirteen two-digit-prefix layer certificates (Agent #113).

The layer semantics mirror Agent113.TwoDigit.Cert.Checked exactly:
  layer 0     = {(a, b, c) : 0 <= c <= 9}
  layer 1     = {w in box : exists e in {0,1}, topT w e = 0 and nextT w e in layer 0}
  layer r + 1 = {w in box : exists e in {0,1}, nextT w e in layer r}      (r >= 1)
  box         = {(s0, s1, s2) : 1 <= s0 <= 18, 0 <= s1, s2 <= 18}
The certificate lists layers 0 .. h-1, where layer h is the first empty one.
This program is untrusted: the Lean kernel re-checks every closure condition.
Python standard library only.
"""
import itertools, json, sys, hashlib

def hi2(s2, e): return (s2 + e) // 10
def hi1(s1, s2, e): return (s1 + hi2(s2, e)) // 10
def top(s0, s1, s2, e): return (s0 + hi1(s1, s2, e)) // 10

def next_triple(s0, s1, s2, e):
    if top(s0, s1, s2, e) == 0:
        return (s0 % 10 + (s0 + hi1(s1, s2, e)) % 10,
                (s1 + s0 // 10) % 10 + (s1 + hi2(s2, e)) % 10,
                (s2 + (s1 + s0 // 10) // 10) % 10 + (s2 + e) % 10)
    return (s0 % 10 + 1,
            (s1 + s0 // 10) % 10 + (s0 + hi1(s1, s2, e)) % 10,
            (s2 + (s1 + s0 // 10) // 10) % 10 + (s1 + hi2(s2, e)) % 10)

BOX = [(a, b, c) for a in range(1, 19) for b in range(19) for c in range(19)]

def layers(a, b, cap=200):
    S = [set((a, b, c) for c in range(10))]
    S.append(set(w for w in BOX for e in (0, 1)
                 if top(*w, e) == 0 and next_triple(*w, e) in S[0]))
    while S[-1]:
        if len(S) > cap:
            raise RuntimeError("no closure")
        cur = S[-1]
        S.append(set(w for w in BOX for e in (0, 1) if next_triple(*w, e) in cur))
    return [sorted(s) for s in S[:-1]]

def T(n): return n + int(str(n)[::-1])
def tri3(m): return (m % 10 + m // 100 % 10, 2 * (m // 10 % 10), m // 100 % 10 + m % 10)

def short_ok(L):
    h = len(L)
    for m in range(1, 100):
        s = T(m)
        if s < 100: continue
        assert s < 1000
        for r in range(1, h):
            if tri3(s) in set(L[r]): return False
    return True

PREFIXES = {(1, 0): 1, (2, 0): 2, (3, 2): 2, (4, 0): 3, (4, 1): 3, (6, 0): 3,
            (6, 4): 3, (6, 5): 6, (7, 6): 3, (8, 0): 4, (8, 1): 4, (8, 2): 4,
            (8, 3): 4}
SHARP = {(1, 0): 100, (2, 0): 1005000, (3, 2): 12090, (4, 0): 1008000,
         (4, 1): 1008400, (6, 0): 1103090, (6, 4): 1203090, (6, 5): 1203290,
         (7, 6): 17590, (8, 0): 1009000, (8, 1): 1009200, (8, 2): 1006500,
         (8, 3): 1009400}

def code(w): return w[0] * 361 + w[1] * 19 + w[2]

def mask(layer):
    m = 0
    for w in layer:
        m |= 1 << code(w)
    return m

def cover18(name, kind):
    return "cover18 " + " ".join(f"{name}_{kind}_{a}" for a in range(1, 19))

def main(outdir):
    summary = {}
    for (a, b), h in sorted(PREFIXES.items()):
        L = layers(a, b)
        assert len(L) == h, ((a, b), len(L), h)
        assert short_ok(L), (a, b)
        name = f"{a}{b}"
        comment = "\n".join(f"  layer {r}: " + " ".join(f"({x},{y},{z})" for x, y, z in lay)
                            for r, lay in enumerate(L))
        masks = ",\n    ".join(str(mask(lay)) for lay in L)
        rows = []
        for aa in range(1, 19):
            rows.append(f"theorem c{name}_first_{aa} : cert{name}.firstRow {aa} = true := by decide +kernel")
        for r in range(1, h):
            for aa in range(1, 19):
                rows.append(f"theorem c{name}_step{r}_{aa} : cert{name}.stepRow {r} {aa} = true := by decide +kernel")
        if h == 1:
            rest = "  intro r h1 h2\n  have h2' : r < 1 := h2\n  omega"
        else:
            alts = " ∨ ".join(f"r = {r}" for r in range(1, h))
            pats = " | ".join("rfl" for _ in range(1, h))
            cases = "\n".join(f"  · exact {cover18('c' + name, f'step{r}')}" for r in range(1, h))
            rest = (f"  intro r h1 h2\n  have h2' : r < {h} := h2\n"
                    f"  have : {alts} := by omega\n  rcases this with {pats}\n{cases}")
        rest = "\n".join("  " + line for line in rest.split("\n"))
        src = f"""import TwoDigitCertificate

/-! Generated by generator/gen_certificates.py (Agent #113). The layer data
are untrusted; every obligation below is evaluated by the Lean kernel
(`decide +kernel`; no compiler-trusted evaluation). Layers, outermost pair sum first:

{comment}
-/

namespace Agent113.TwoDigit

def cert{name} : Cert where
  a := {a}
  b := {b}
  layers := [{masks}]

theorem c{name}_base : cert{name}.baseCheck = true := by decide +kernel
theorem c{name}_short : cert{name}.shortCheck = true := by decide +kernel
{chr(10).join(rows)}

theorem cert{name}_checked : cert{name}.Checked where
  base := c{name}_base
  first := {cover18('c' + name, 'first')}
  rest := by
{rest}
  short := c{name}_short

/-- Every palindrome whose canonical numeral begins with the digits {a}, {b}
has ancestry depth at most {h}: for every positive start `A`, if
`orbit A t` is such a palindrome then `t ≤ {h}`. Any width, any interior. -/
theorem ancestry_bound_{name} :
    ∀ A P t, 0 < A → PalindromeStartsTwo {a} {b} P → Lychrel196.orbit A t = P → t ≤ {h} :=
  cert{name}.ancestry_bound (by decide) cert{name}_checked

#print axioms cert{name}_checked
#print axioms ancestry_bound_{name}

end Agent113.TwoDigit
"""
        with open(f"{outdir}/TwoDigitCert{name}.lean", "w") as f:
            f.write(src)
        summary[name] = {"prefix": [a, b], "bound": h, "layer_sizes": [len(x) for x in L],
                         "layers": L, "sharp_root": SHARP[(a, b)],
                         "row_theorems": 18 * h}
    with open(f"{outdir}/generator/certificates.json", "w") as f:
        json.dump(summary, f, indent=1, sort_keys=True)
    print(json.dumps({k: (v["bound"], v["layer_sizes"]) for k, v in summary.items()}))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
