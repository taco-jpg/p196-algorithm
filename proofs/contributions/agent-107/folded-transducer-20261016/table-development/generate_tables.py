#!/usr/bin/env python3
"""Extract original AST nodes, retain exact tables, and generate kernel-checkable Lean data."""
import ast
from collections import Counter
import hashlib
import json
from pathlib import Path
import subprocess
import types

REPO = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parent
DIRECT = REPO / 'proofs/creative_regular_direct__8988fd8c6a0aad92.py'
WEIGHTED = REPO / 'proofs/persist_spacetime_weighted__d53dd1c09dcfc34a.py'
INVARIANT = REPO / 'proofs/creative_regular_invariant__ea923cdb26a39825.py'
DEFS = REPO / 'proofs/Agent107TransducerDefs.lean'

def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def extract_functions(path, names, context):
    tree = ast.parse(path.read_text())
    nodes = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name in names]
    assert {n.name for n in nodes} == set(names)
    exec(compile(ast.Module(body=nodes, type_ignores=[]), str(path), 'exec'), context)

arith = {}
extract_functions(INVARIANT, {'C', 'D'}, arith)
context = {'r': types.SimpleNamespace(C=arith['C'], D=arith['D'])}
extract_functions(DIRECT, {'fst_graph'}, context)
states, edges = context['fst_graph']()
context.update(FS=states, FE=edges)
nodes = ast.parse(WEIGHTED.read_text()).body
start = next(i for i,n in enumerate(nodes) if isinstance(n, ast.Assign)
             and any(isinstance(t, ast.Name) and t.id == 'TERMS' for t in n.targets))
stop = next(i for i,n in enumerate(nodes) if isinstance(n, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id == 'NW' for t in n.targets))
exec(compile(ast.Module(body=nodes[start:stop+1], type_ignores=[]), str(WEIGHTED), 'exec'), context)
terms = context['TS']

# Independent finite comparison against the locked Lean predicates' literal arithmetic.
assert len(states) == len(set(states))
assert len(edges) == len(set(edges))
assert len(terms) == len(set(terms))
independent_edges = []
independent_terms = []
for i,(h,a,b,d,started) in enumerate(states):
    for q in range(19):
        for bn in range(2):
            if (started or q > 0) and (q+bn)//10 == b:
                target = (h,(q+a)//10,bn,-1 if h == 0 else (q+bn)%10,True)
                out = (q+a)%10 + ((q+bn)%10 if h == 0 else max(d,0))
                assert target in states
                independent_edges.append((i,q,out,states.index(target)))
    for center in [None,*range(19)]:
        if not (started or (center or 0)>0): continue
        if center is None:
            valid = a == b
        else:
            valid = center % 2 == 0 and (center+a)//10 == b
        if valid:
            extra = None if h == 0 or center is None else (center+a)%10+max(d,0)
            oc = (None if center is None else 2*((center+a)%10)) if h == 0 else (2*max(d,0) if center is None else None)
            independent_terms.append((i,center,extra,oc))
assert edges == independent_edges
assert terms == independent_terms

record = dict(states=states, edges=edges, terminals=terms,
              counts=dict(states=len(states),edges=len(edges),terminals=len(terms)),
              source_commit=subprocess.check_output(['git','-C',str(REPO),'rev-parse','HEAD'],text=True).strip(),
              sources={str(p.relative_to(REPO)):dict(sha256=sha(p),git_blob=subprocess.check_output(['git','-C',str(REPO),'hash-object',str(p)],text=True).strip()) for p in [DIRECT,WEIGHTED,INVARIANT,DEFS]},
              extraction='Executed only original C/D and fst_graph AST function nodes, plus original TERMS/TS/NW top-level AST block. No solver imports or algorithm edits.',
              independent_comparison='Exact ordered equality with separately enumerated locked Lean transition/terminal arithmetic over every listed state and all bounded choices.')
(HERE/'extracted-tables.json').write_text(json.dumps(record,indent=2)+'\n')

def opt(n): return 'none' if n is None else f'(some {n})'
def st(s):
    h,a,b,d,started=s
    return f'⟨{h}, {a}, {b}, {d if d >= 0 else "("+str(d)+")"}, {str(started).lower()}⟩'

lines=['import Agent107TransducerDefs','', '/-! Literal original finite folded transducer tables; generated by the retained AST extractor.',
       'Every finite claim below is discharged by Lean kernel reduction, without native_decide. -/', '',
       'namespace Agent107.FoldedTransducer.Table', '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '',
       'structure Edge where', '  source : State', '  input : Nat', '  output : Nat', '  target : State', '  deriving DecidableEq, Repr', '',
       'structure TerminalRow where', '  source : State', '  center : Option Nat', '  extra : Option Nat', '  outputCenter : Option Nat', '  deriving DecidableEq, Repr','']
for i,s in enumerate(states): lines += [f'def state{i} : State := {st(s)}']
lines += ['', 'def states : List State := ['+', '.join(f'state{i}' for i in range(len(states)))+']','',
          'def centers : List (Option Nat) := none :: (List.range 19).map some','']
for i in range(len(states)):
    ee=[e for e in edges if e[0]==i]
    tt=[t for t in terms if t[0]==i]
    lines += [f'def edges{i} : List Edge := [']
    lines += [f'  ⟨state{x}, {q}, {out}, state{y}⟩'+(',' if j+1<len(ee) else '') for j,(x,q,out,y) in enumerate(ee)]
    lines += [']','',f'def terminals{i} : List TerminalRow := [']
    lines += [f'  ⟨state{x}, {opt(c)}, {opt(extra)}, {opt(oc)}⟩'+(',' if j+1<len(tt) else '') for j,(x,c,extra,oc) in enumerate(tt)]
    lines += [']','']
lines += ['def edgeRows : List (List Edge) := ['+', '.join(f'edges{i}' for i in range(len(states)))+']',
          'def terminalRows : List (List TerminalRow) := ['+', '.join(f'terminals{i}' for i in range(len(states)))+']',
          'def edges : List Edge := edgeRows.flatten',
          'def terminals : List TerminalRow := terminalRows.flatten','',
          f'theorem states_length : states.length = {len(states)} := by decide',
          f'theorem edges_length : edges.length = {len(edges)} := by decide',
          f'theorem terminals_length : terminals.length = {len(terms)} := by decide',
          'theorem states_nodup : states.Nodup := by decide',
          'theorem starts_mem (h : Nat) (hh : h ≤ 1) : initial h ∈ states := by',
          '  have hcases : h = 0 ∨ h = 1 := by omega',
          '  rcases hcases with rfl | rfl <;> decide','']

for i in range(len(states)):
    lines += [f'theorem row{i}_separated : edges{i}.Nodup ∧ ∀ e ∈ edges{i}, e.source = state{i} := by decide',
              f'theorem terminal_row{i}_separated : terminals{i}.Nodup ∧ ∀ r ∈ terminals{i}, r.source = state{i} := by decide','',
              f'theorem row{i}_sound : ∀ e ∈ edges{i},',
              '    e.source ∈ states ∧ e.target ∈ states ∧',
              '    Transition e.source e.input e.target ∧ e.output = emit e.source e.input e.target.high := by decide','',
              f'theorem row{i}_complete : ∀ (q : Fin 19) (b : Fin 2),',
              f'    (state{i}.started = false → 0 < q.val) → (q.val + b.val) / 10 = state{i}.high →',
              f'    (⟨state{i}, q.val, emit state{i} q.val b.val, nextState state{i} q.val b.val⟩ : Edge) ∈ edges{i} := by decide','',
              f'theorem terminal_row{i}_sound : ∀ r ∈ terminals{i},',
              '    r.source ∈ states ∧ Terminal r.source r.center ∧',
              '    r.extra = terminalExtra r.source r.center ∧ r.outputCenter = terminalCenter r.source r.center := by decide','',
              f'theorem terminal_row{i}_complete : ∀ c ∈ centers, Terminal state{i} c →',
              f'    (⟨state{i}, c, terminalExtra state{i} c, terminalCenter state{i} c⟩ : TerminalRow) ∈ terminals{i} := by decide','']

lines += ['theorem edge_sound (e : Edge) (he : e ∈ edges) :',
          '    e.source ∈ states ∧ e.target ∈ states ∧',
          '    Transition e.source e.input e.target ∧ e.output = emit e.source e.input e.target.high := by',
          '  obtain ⟨row, hr, he⟩ := List.mem_flatten.mp he',
          '  simp only [edgeRows, List.mem_cons, List.mem_nil_iff, or_false] at hr',
          '  rcases hr with '+ ' | '.join('rfl' for _ in states)]
lines += [f'  · exact row{i}_sound e he' for i in range(len(states))]
lines += ['', 'theorem transition_complete (s t : State) (q : Nat)',
          '    (hs : s ∈ states) (h : Transition s q t) :',
          '    (⟨s, q, emit s q t.high, t⟩ : Edge) ∈ edges := by',
          '  rcases h with ⟨hq, hstart, hb, hcarry, ht⟩',
          '  have hqfin : q < 19 := by omega', '  have hbfin : t.high < 2 := by omega',
          '  simp only [states, List.mem_cons, List.mem_nil_iff, or_false] at hs',
          '  rcases hs with '+ ' | '.join('rfl' for _ in states)]
for i in range(len(states)):
    lines += [f'  · have hc := row{i}_complete ⟨q, hqfin⟩ ⟨t.high, hbfin⟩ hstart hcarry',
              '    change (⟨_, q, _, nextState _ q t.high⟩ : Edge) ∈ _ at hc',
              '    rw [← ht] at hc',
              f'    exact List.mem_flatten.mpr ⟨edges{i}, by simp [edgeRows], hc⟩']
lines += ['', 'theorem states_closed (s t : State) (q : Nat) (hs : s ∈ states)',
          '    (h : Transition s q t) : t ∈ states :=',
          '  (edge_sound _ (transition_complete s t q hs h)).2.1','',
          'theorem terminal_sound (r : TerminalRow) (hr : r ∈ terminals) :',
          '    r.source ∈ states ∧ Terminal r.source r.center ∧',
          '    r.extra = terminalExtra r.source r.center ∧ r.outputCenter = terminalCenter r.source r.center := by',
          '  obtain ⟨row, hrow, hr⟩ := List.mem_flatten.mp hr',
          '  simp only [terminalRows, List.mem_cons, List.mem_nil_iff, or_false] at hrow',
          '  rcases hrow with '+ ' | '.join('rfl' for _ in states)]
lines += [f'  · exact terminal_row{i}_sound r hr' for i in range(len(states))]
lines += ['', 'theorem terminal_center_mem (s : State) (c : Option Nat) (h : Terminal s c) : c ∈ centers := by',
          '  cases c with',
          '  | none => simp [centers]',
          '  | some v =>',
          '    have hv : v ≤ 18 := h.2.1',
          '    simp only [centers, List.mem_cons, Option.some.injEq, List.mem_map]',
          '    exact Or.inr ⟨v, List.mem_range.mpr (by omega), rfl⟩','',
          'theorem terminal_complete (s : State) (c : Option Nat)',
          '    (hs : s ∈ states) (h : Terminal s c) :',
          '    (⟨s, c, terminalExtra s c, terminalCenter s c⟩ : TerminalRow) ∈ terminals := by',
          '  have hc := terminal_center_mem s c h',
          '  simp only [states, List.mem_cons, List.mem_nil_iff, or_false] at hs',
          '  rcases hs with '+ ' | '.join('rfl' for _ in states)]
lines += [f'  · exact List.mem_flatten.mpr ⟨terminals{i}, by simp [terminalRows], terminal_row{i}_complete c hc h⟩' for i in range(len(states))]
lines += ['',
          'theorem edge_mem_iff (s t : State) (q o : Nat) :',
          '    (⟨s, q, o, t⟩ : Edge) ∈ edges ↔',
          '      s ∈ states ∧ Transition s q t ∧ o = emit s q t.high := by',
          '  constructor',
          '  · intro h',
          '    have he := edge_sound _ h',
          '    exact ⟨he.1, he.2.2.1, he.2.2.2⟩',
          '  · rintro ⟨hs, h, rfl⟩',
          '    exact transition_complete s t q hs h','',
          'theorem terminal_mem_iff (s : State) (c extra oc : Option Nat) :',
          '    (⟨s, c, extra, oc⟩ : TerminalRow) ∈ terminals ↔',
          '      s ∈ states ∧ Terminal s c ∧ extra = terminalExtra s c ∧ oc = terminalCenter s c := by',
          '  constructor',
          '  · intro h',
          '    exact terminal_sound _ h',
          '  · rintro ⟨hs, h, rfl, rfl⟩',
          '    exact terminal_complete s c hs h','',
          '#print axioms states_nodup', '#print axioms edges_nodup', '#print axioms terminals_nodup',
          '#print axioms starts_mem', '#print axioms edge_sound', '#print axioms transition_complete',
          '#print axioms states_closed', '#print axioms terminal_sound', '#print axioms terminal_complete',
          '#print axioms edge_mem_iff', '#print axioms terminal_mem_iff','',
          'end Agent107.FoldedTransducer.Table','']
cut1 = lines.index('theorem row0_separated : edges0.Nodup ∧ ∀ e ∈ edges0, e.source = state0 := by decide')
cut2 = lines.index('theorem edge_sound (e : Edge) (he : e ∈ edges) :')
data_lines = lines[:cut1] + ['end Agent107.FoldedTransducer.Table','']
header = ['namespace Agent107.FoldedTransducer.Table','','set_option maxRecDepth 200000','set_option maxHeartbeats 0','']
check_lines = ['import Agent107TransducerTablesData',''] + header + lines[cut1:cut2] + ['end Agent107.FoldedTransducer.Table','']
generic = '''theorem nodup_blocks {α β : Type} (key : α → β) (bs : List (β × List α))
    (hn : (bs.map Prod.fst).Nodup)
    (hr : ∀ b ∈ bs, b.2.Nodup ∧ ∀ x ∈ b.2, key x = b.1) :
    (bs.flatMap Prod.snd).Nodup := by
  induction bs with
  | nil => exact List.Pairwise.nil
  | cons b bs ih =>
    have hk := List.pairwise_cons.mp hn
    have hb := hr b (by simp)
    have ht : ∀ c ∈ bs, c.2.Nodup ∧ ∀ x ∈ c.2, key x = c.1 := by
      intro c hc
      exact hr c (List.mem_cons_of_mem _ hc)
    change (b.2 ++ bs.flatMap Prod.snd).Pairwise (fun x y => x ≠ y)
    apply List.pairwise_append.mpr
    refine ⟨hb.1, ih hk.2 ht, ?_⟩
    intro x hx y hy heq
    obtain ⟨c, hc, hy⟩ := List.mem_flatMap.mp hy
    have hne := hk.1 c.1 (List.mem_map.mpr ⟨c, hc, rfl⟩)
    exact hne ((hb.2 x hx).symm.trans ((congrArg key heq).trans ((ht c hc).2 y hy)))
'''.splitlines()
generic += ['', 'def edgeBlocks : List (State × List Edge) := ['+', '.join(f'(state{i}, edges{i})' for i in range(len(states)))+']',
            'def terminalBlocks : List (State × List TerminalRow) := ['+', '.join(f'(state{i}, terminals{i})' for i in range(len(states)))+']','']
for kind,typ,proj in [('edge','Edge','edges'),('terminal','TerminalRow','terminals')]:
    rowname = 'row' if kind == 'edge' else 'terminal_row'
    generic += [f'theorem {proj}_nodup : {proj}.Nodup := by',
                f'  change ({kind}Blocks.flatMap Prod.snd).Nodup',
                f'  apply nodup_blocks {typ}.source {kind}Blocks',
                '  · exact states_nodup',
                '  · intro b hb',
                f'    simp only [{kind}Blocks, List.mem_cons, List.mem_nil_iff, or_false] at hb',
                '    rcases hb with '+ ' | '.join('rfl' for _ in states)]
    generic += [f'    · exact {rowname}{i}_separated' for i in range(len(states))]
    generic += ['']
public_lines = ['import Agent107TransducerTablesChecks','']+header+generic+lines[cut2:]
outputs = {
    'Agent107TransducerTablesData.lean': data_lines,
    'Agent107TransducerTablesChecks.lean': check_lines,
    'Agent107TransducerTables.lean': public_lines,
}
for name,content in outputs.items():
    (REPO/'proofs'/name).write_text('\n'.join(content))
record['generated_lean_sha256'] = {name:sha(REPO/'proofs'/name) for name in outputs}
record['generator_sha256'] = sha(Path(__file__))
(HERE/'extraction-manifest.json').write_text(json.dumps({k:v for k,v in record.items() if k not in ['states','edges','terminals']},indent=2)+'\n')
print(json.dumps(record['counts']))
print('Generated:',', '.join(outputs))
