#!/usr/bin/env python3
"""Produce transparent Lean rank data and exhaustive kernel-checkable claims.

The input supplies only candidate ranks. The generated proofs independently
evaluate SixPrefix.step on every input and verify strict decrease. No edge
listed in the input certificate is assumed by a Lean theorem.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
from pathlib import Path
import struct

HERE = Path(__file__).resolve().parent
DEFAULT_SOURCE = HERE.parent / "2026-10-14-seven-step-extension/direct_six_graph.bin.gz"
PHASES = ((4, 4, 0), (8, 8, 0), (16, 16, 0), (7, 14, 7),
          (15, 8, 15), (6, 14, 14), (13, 9, 9))
OVERFLOWS = (0, 0, 1, 0, 1, 0, 1)


def match_function(name: str, args: str, values: list[str], default: str) -> str:
    lines = [f"def {name} {args}"]
    lines.extend(f"  | {i} => {value}" for i, value in enumerate(values))
    lines.append(f"  | _ => {default}")
    return "\n".join(lines) + "\n\n"


def generate(source: Path, output: Path, chunk_limit: int | None) -> None:
    compressed = source.read_bytes()
    raw = gzip.decompress(compressed)
    assert raw[:8] == b"P196DAG1"
    vertices, edges = struct.unpack_from("<II", raw, 8)
    assert vertices == 7 * 19 ** 3
    assert len(raw) == 16 + 4 * vertices + 9 * edges
    ranks = struct.unpack_from(f"<{vertices}I", raw, 16)
    assert max(ranks[:19 ** 3]) == 26
    row_ids: dict[tuple[int, ...], int] = {}
    table_ids: dict[tuple[int, ...], int] = {}
    phase_tables = []
    for phase in range(7):
        phase_row = []
        for a in range(19):
            table = []
            for b in range(19):
                offset = phase * 19 ** 3 + a * 19 ** 2 + b * 19
                row = ranks[offset:offset + 19]
                row_id = row_ids.setdefault(row, len(row_ids))
                table.append(row_id)
            table_id = table_ids.setdefault(tuple(table), len(table_ids))
            phase_row.append(table_id)
        phase_tables.append(phase_row)

    header = f'''import SixPrefix
import BoundaryTransducer

/-!
Transparent candidate ranks for the exact six-coordinate boundary graph.
Generated by generate_rank_certificate.py from a finite candidate table.
The generator is not trusted: each decrease claim is decided by Lean's kernel.
Candidate compressed SHA-256: {hashlib.sha256(compressed).hexdigest()}
Candidate raw SHA-256: {hashlib.sha256(raw).hexdigest()}
-/

namespace RankCertificate

set_option maxRecDepth 100000
set_option maxHeartbeats 0

'''
    parts = [header]
    parts.append(match_function("phasePrefix", ": Nat → BoundaryTransducer.Prefix",
                                [f"⟨{a}, {b}, {c}⟩" for a, b, c in PHASES], "⟨4, 4, 0⟩"))
    parts.append(match_function("phaseOverflow", ": Nat → Nat",
                                list(map(str, OVERFLOWS)), "0"))
    parts.append('''def assemble (phase a b c : Nat) : SixPrefix.Prefix6 :=
  let p := phasePrefix phase
  ⟨p.a, p.b, p.c, a, b, c⟩

def first3 (p : SixPrefix.Prefix6) : BoundaryTransducer.Prefix :=
  ⟨p.x0, p.x1, p.x2⟩

''')
    for row, row_id in row_ids.items():
        parts.append(match_function(f"row{row_id}", ": Nat → Nat", list(map(str, row)), "0"))
    for table, table_id in table_ids.items():
        parts.append(match_function(f"table{table_id}", ": Nat → Nat → Nat",
                                    [f"row{i}" for i in table], "fun _ => 0"))
    for phase, table in enumerate(phase_tables):
        parts.append(match_function(f"phase{phase}", ": Nat → Nat → Nat → Nat",
                                    [f"table{i}" for i in table], "fun _ _ => 0"))
    parts.append(match_function("rank", ": Nat → Nat → Nat → Nat → Nat",
                                [f"phase{i}" for i in range(7)], "fun _ _ _ => 0"))
    parts.append('''/-- The conclusion independently recomputes the exact transition. -/
abbrev EdgeGood (phase a b c : Nat) (control : Bool) : Prop :=
  let result := SixPrefix.step (assemble phase a b c) control
  (first3 result.1 = phasePrefix ((phase + 1) % 7) ∧
    result.2 = phaseOverflow phase) →
    rank ((phase + 1) % 7) result.1.x3 result.1.x4 result.1.x5 < rank phase a b c

''')
    output.mkdir(parents=True, exist_ok=True)
    (output / "RankData.lean").write_text("".join(parts) + "end RankCertificate\n")

    chunks = []
    phase_chunks = [[] for _ in range(7)]
    for phase in range(7):
        for a in range(19):
            if chunk_limit is not None and len(chunks) >= chunk_limit:
                break
            chunk = f'''theorem check_{phase}_{a} : ∀ b c : Fin 19, ∀ control : Bool,
    EdgeGood {phase} {a} b.val c.val control := by decide

'''
            if phase == 0:
                chunk += f'''theorem bound_0_{a} : ∀ b c : Fin 19,
    rank 0 {a} b.val c.val ≤ 26 := by decide

'''
            chunks.append(chunk)
            phase_chunks[phase].append(chunk)
    for phase, own_chunks in enumerate(phase_chunks):
        checks = "import RankData\n\nnamespace RankCertificate\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n" + "".join(own_chunks)
        checks += "end RankCertificate\n"
        (output / f"RankChecks{phase}.lean").write_text(checks)
    imports = "".join(f"import RankChecks{i}\n" for i in range(7))
    (output / "RankChecks.lean").write_text(imports)

    if chunk_limit is None:
        final = '''import RankChecks

/-!
Kernel-checked finite descent for all 48,013 vertices and both Boolean
inputs. The hypotheses are precisely the next phase's three-coordinate
prefix and this phase's overflow. Every transition is recomputed using
SixPrefix.step; the candidate graph's listed edges are never assumed.
-/

namespace RankCertificate

set_option maxHeartbeats 0
set_option maxRecDepth 100000

private theorem split19 (n : Nat) (hn : n < 19) :
    ''' + " ∨ ".join(f"n = {i}" for i in range(19)) + ''' := by omega

theorem rank_decreases (phase a b c : Nat) (control : Bool)
    (hphase : phase < 7) (ha : a < 19) (hb : b < 19) (hc : c < 19)
    (hfront : first3 (SixPrefix.step (assemble phase a b c) control).1 =
      phasePrefix ((phase + 1) % 7))
    (hoverflow : (SixPrefix.step (assemble phase a b c) control).2 =
      phaseOverflow phase) :
    rank ((phase + 1) % 7)
      (SixPrefix.step (assemble phase a b c) control).1.x3
      (SixPrefix.step (assemble phase a b c) control).1.x4
      (SixPrefix.step (assemble phase a b c) control).1.x5 < rank phase a b c := by
  have hphaseCases : ''' + " ∨ ".join(f"phase = {i}" for i in range(7)) + ''' := by omega
  rcases hphaseCases with ''' + " | ".join("rfl" for _ in range(7)) + "\n"
        for phase in range(7):
            final += "  · rcases split19 a ha with " + " | ".join("rfl" for _ in range(19)) + "\n"
            for a in range(19):
                final += f"    · exact check_{phase}_{a} ⟨b, hb⟩ ⟨c, hc⟩ control ⟨hfront, hoverflow⟩\n"
        final += '''
theorem phase0_bound (a b c : Nat) (ha : a < 19) (hb : b < 19) (hc : c < 19) :
    rank 0 a b c ≤ 26 := by
  rcases split19 a ha with ''' + " | ".join("rfl" for _ in range(19)) + "\n"
        for a in range(19):
            final += f"  · exact bound_0_{a} ⟨b, hb⟩ ⟨c, hc⟩\n"
        final += '''
#print axioms rank_decreases
#print axioms phase0_bound

end RankCertificate
'''
        (output / "RankCertificate.lean").write_text(final)
    print(f"Generated {len(row_ids)} rank rows, {len(table_ids)} tables, {len(chunks)} chunks")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=HERE)
    parser.add_argument("--chunk-limit", type=int)
    args = parser.parse_args()
    generate(args.source, args.output, args.chunk_limit)
